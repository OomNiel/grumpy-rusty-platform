#!/usr/bin/env python3
"""Rasterise DejaVu Sans Mono into the integer tables the crate's small faces use.

Run once, and commit the output:

    python3 crates/embedded-gui/assets/fonts/from_truetype.py

Why a generated table and not a Truetype file: the board has no font engine. A face is a grid of bits,
and a TTF would cost more code to load than the whole toolkit weighs. So the pixels are baked once,
here, and the result is a text file anybody can read and diff.

Why monochrome (`getmask(..., mode='1')`) and not the anti-aliased default: FreeType's monochrome
rasteriser grid-fits the outlines -- stems land on whole pixels -- which is the difference between a
crisp letter and grey mush at 9 to 13 pixels. The anti-aliased version was tried first and looked
worse at every size than the hand-drawn 3x5 it was meant to replace.

Sizes were chosen by eye and then measured: below a 9 px em the rasterised letterforms collapse
(`a`, `e`, `s` become the same blob), so the smallest face here is 6 wide by 10 tall rather than the
5x7 that was asked for. A 5x7 works when the glyphs are *drawn* at 5x7; rasterising an outline face
that small does not.

Licence: DejaVu fonts are under the Bitstream Vera licence, which permits redistribution and
modification provided the copyright notice travels with it. `DejaVu-LICENSE.txt` is that notice.
"""

from pathlib import Path

from PIL import Image, ImageFont

SOURCE = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FIRST_CHAR = 32
LAST_CHAR = 126
HERE = Path(__file__).resolve().parent

# (file, TTF pixel size, cell width, cell height, baseline row, advance, line height)
FACES = [
    ("dejavu_6x10.txt", 9, 6, 10, 8, 7, 12),
    ("dejavu_8x16.txt", 12, 8, 16, 11, 9, 19),
]


def glyph_cell(font, ch, width, height, baseline, shift):
    """One glyph, as `height` rows of `width` bits, placed on the shared baseline."""
    cell = [[0] * width for _ in range(height)]
    if ch == " ":
        return cell
    mask, (ox, oy) = font.getmask2(ch, mode="1", anchor="ls")
    w, h = mask.size
    if w == 0 or h == 0:
        return cell
    ink = Image.frombytes("L", (w, h), bytes(mask)).load()
    for y in range(h):
        row = baseline + oy + y
        if not 0 <= row < height:
            raise SystemExit(f"{ch!r}: row {row} is outside a {width}x{height} cell")
        for x in range(w):
            col = ox + x + shift
            if not 0 <= col < width:
                raise SystemExit(f"{ch!r}: column {col} is outside a {width}x{height} cell")
            if ink[x, y]:
                cell[row][col] = 1
    return cell


def render(name, size, width, height, baseline, advance, line_height):
    font = ImageFont.truetype(SOURCE, size)
    chars = [chr(code) for code in range(FIRST_CHAR, LAST_CHAR + 1)]

    # Monospace, so one shift suits every glyph: centre the widest ink in the cell.
    left, right = 0, 0
    for ch in chars:
        if ch == " ":
            continue
        _, (ox, oy) = font.getmask2(ch, mode="1", anchor="ls")
        mask, _ = font.getmask2(ch, mode="1", anchor="ls")
        w = mask.size[0]
        if w == 0:
            continue
        left = min(left, ox)
        right = max(right, ox + w)
    shift = (width - (right - left)) // 2 - left

    lines = [
        "# %s -- generated by from_truetype.py, do not edit." % name,
        "# DejaVu Sans Mono at %d px, %dx%d cell, baseline row %d, advance %d, line height %d."
        % (size, width, height, baseline, advance, line_height),
        "# Format: key:row0,row1,... -- one row per line of the cell, '1' is ink.",
        "",
    ]
    for ch in chars:
        cell = glyph_cell(font, ch, width, height, baseline, shift)
        rows = ",".join("".join(str(bit) for bit in row) for row in cell)
        lines.append("%s:%s" % ("space" if ch == " " else ch, rows))
    (HERE / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {name}: {LAST_CHAR - FIRST_CHAR + 1} glyphs of {width}x{height}")


for face in FACES:
    render(*face)
