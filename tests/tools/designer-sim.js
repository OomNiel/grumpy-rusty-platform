#!/usr/bin/env node
'use strict';

/**
 * The designer's canvas-to-glass check.
 *
 *   node tests/tools/designer-sim.js            # regenerate, compile and measure
 *   node tests/tools/designer-sim.js --no-run   # just regenerate the markup and expectations
 *
 * Why this exists: the designer emits markup with no absolute positioning -- a widget becomes a grid
 * placement across pixel tracks -- and whether that lands on the designed rectangle is a property of
 * `embedded-gui`'s layout engine rather than of our arithmetic. TypeScript can prove the tracks add up
 * (the t1 layer does), but only a render can prove the engine puts the widget there. So this tool takes the
 * fixture, runs it through the extension's *own* emitter, and hands the result to a real `include_gui!`
 * build that measures every widget with `absolute_rect`.
 *
 * The generated files are written into `tests/sim/` and are checked in, so a reviewer can see exactly what
 * was measured without running anything. They are regenerated on every run, so they cannot go stale.
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { compiled, repoRoot } = require('../lib/harness');

const { defaultProps, defaultChildren, createDocument, validateDocument } = compiled('designer/model');
const { emitKdl } = compiled('designer/kdl');
const { isBuiltInFont } = compiled('designer/fonts');
const { widgetSpec } = compiled('designer/catalog');
const { rustFieldName } = compiled('designer/model');
const { widgetAddressable } = compiled('designer/catalog');
const { starterDocument, emitStarterKdl, emitUiRs, DESIGNER_FILES } = compiled('designer/generate');
const { designCanvasSize } = compiled('designer/model');

const SIM_DIR = path.join(repoRoot(), 'tests', 'sim');
const FIXTURE = path.join(SIM_DIR, 'fixture.json');
const SCREEN = path.join(SIM_DIR, 'screens', 'panel.kdl');
/** The same design with no font declared and no reference to one, for the pixel difference. */
const SCREEN_NO_FONT = path.join(SIM_DIR, 'screens', 'panel-nofont.kdl');
const EXPECTATIONS = path.join(SIM_DIR, 'src', 'expectations.rs');
/** Shared with the other cargo-driven layers: an ambient CARGO_TARGET_DIR must never redirect the output. */
const TARGET_DIR = path.join(repoRoot(), 'tests', 'out', 'sim-target');
const CARGO_HOME = path.join(repoRoot(), 'tests', 'tmp', 'cargo-home');

/** `#rrggbb` to the 5/6/5 triple `Rgb565::new` wants, which is what the crate's own parser computes. */
function rgb565(hex) {
    const value = hex.replace('#', '');
    const r = parseInt(value.slice(0, 2), 16) >> 3;
    const g = parseInt(value.slice(2, 4), 16) >> 2;
    const b = parseInt(value.slice(4, 6), 16) >> 3;
    return { r, g, b };
}

/** The fixture lists only what differs from the catalogue's defaults. */
function documentFromFixture(fixture) {
    const document = createDocument({
        boardId: fixture.boardId,
        panelWidth: fixture.panelWidth,
        panelHeight: fixture.panelHeight,
        rotation: fixture.rotation,
        screenId: fixture.screenId,
    });
    document.theme = fixture.theme ?? 'dark';
    document.fonts = (fixture.fonts ?? []).map((font) => ({ id: font.id, src: font.src, chars: font.chars }));
    document.widgets = fixture.widgets.map((entry) => ({
        id: entry.id,
        tag: entry.tag,
        x: entry.x,
        y: entry.y,
        width: entry.width,
        height: entry.height,
        props: { ...defaultProps(entry.tag), ...(entry.props ?? {}) },
        events: entry.events ?? [],
        children: defaultChildren(entry.tag),
    }));
    return document;
}

/** The widgets the design gives a *declared* font to, which is the route the markup has an attribute for. */
function declaredFontWidgets(document) {
    return document.widgets.filter(
        (widget) =>
            typeof widget.props.font === 'string' &&
            widget.props.font !== '' &&
            !isBuiltInFont(widget.props.font),
    );
}

function expectationSource(document, kdl, fixture) {
    const canvas = kdl.match(/width=(\d+) height=(\d+)/);
    const probeWidget = document.widgets.find((widget) => widget.id === fixture.probe.widget);
    if (probeWidget === undefined) {
        throw new Error(`the fixture probes "${fixture.probe.widget}", which is not a widget in it`);
    }
    const colour = rgb565(String(probeWidget.props.fill ?? probeWidget.props.bg ?? '#000000'));

    const lines = [];
    lines.push('// Generated by tests/tools/designer-sim.js from tests/sim/fixture.json. DO NOT EDIT.');
    lines.push('//');
    lines.push('// One line per widget: the name, its generated struct field, and the rectangle the canvas placed it');
    lines.push('// at. The simulator compares each against what the layout engine reports.');
    lines.push('');
    lines.push(`pub const CANVAS_W: u32 = ${canvas[1]};`);
    lines.push(`pub const CANVAS_H: u32 = ${canvas[2]};`);
    lines.push('');
    lines.push('/// Where to look for paint, and what colour the widget under it was filled with.');
    lines.push(
        `pub const EXPECTED_FILL: (i32, i32, Rgb565) = (${fixture.probe.x}, ${fixture.probe.y}, ` +
            `Rgb565::new(${colour.r}, ${colour.g}, ${colour.b}));`,
    );
    lines.push('');
    lines.push('/// The probed widget\'s own rectangle, so a failure can show what was painted inside it.');
    lines.push(
        `pub const PROBE_RECT: (i32, i32, u32, u32) = (${probeWidget.x}, ${probeWidget.y}, ` +
            `${probeWidget.width}, ${probeWidget.height});`,
    );
    lines.push('');
    // A reference point just outside the widget. Comparing the two proves the widget painted something at
    // its own rectangle, which is the claim that does not depend on how the theme resolves colours.
    const referenceX = probeWidget.x > 4 ? probeWidget.x - 4 : probeWidget.x + probeWidget.width + 4;
    const fonted = declaredFontWidgets(document)[0];
    if (fonted === undefined) {
        throw new Error('the fixture has no widget using a font, so there is nothing for the difference to measure');
    }
    // The font difference is measured by its own bin, which has neither of the other bins' modules, so it gets
    // its own consts file rather than a slice of this one.
    lines.push('/// The widget the design gives a font to: what the two renders must disagree about.');
    lines.push(
        `pub const FONTED_RECT: (i32, i32, u32, u32) = (${fonted.x}, ${fonted.y}, ${fonted.width}, ${fonted.height});`,
    );
    lines.push('');
    lines.push('/// A point just outside the probed widget, to compare paint against.');
    lines.push(`pub const PROBE_REFERENCE: (i32, i32) = (${referenceX}, ${fixture.probe.y});`);
    lines.push('');
    lines.push('/// Every widget, against the engine\'s own answer for where it ended up.');
    lines.push('pub fn check(');
    lines.push('    rect_of: &dyn Fn(WidgetId) -> Option<Rect>,');
    lines.push('    widgets: &crate::screen::SimPanelWidgets,');
    lines.push(') -> Vec<String> {');
    lines.push('    let mut problems: Vec<String> = Vec::new();');
    lines.push('    let mut one = |name: &str, id: WidgetId, x: i32, y: i32, w: u32, h: u32| {');
    lines.push('        match rect_of(id) {');
    lines.push('            None => problems.push(format!("{name}: the engine has no rect for this widget")),');
    lines.push('            Some(rect) => {');
    lines.push('                if rect.x != x || rect.y != y || rect.w != w || rect.h != h {');
    lines.push('                    problems.push(format!(');
    lines.push('                        "{name}: the canvas placed it at ({x}, {y}) {w}x{h}, the engine laid it out at ({}, {}) {}x{}",');
    lines.push('                        rect.x, rect.y, rect.w, rect.h');
    lines.push('                    ));');
    lines.push('                }');
    lines.push('            }');
    lines.push('        }');
    lines.push('    };');
    // A spacer's id is dropped by the parser, so codegen emits no struct field for it and there is nothing
    // to look its rectangle up by. It is still placed -- the t1 layer's round trip covers that -- but it
    // cannot be measured from here.
    const measurable = document.widgets.filter((widget) => widgetAddressable(widget.tag));
    const unaddressable = document.widgets.filter((widget) => !widgetAddressable(widget.tag));
    for (const skipped of unaddressable) {
        lines.push(
            `    // ${JSON.stringify(skipped.id)} (${skipped.tag}) has no generated field: the parser drops its id.`,
        );
    }
    for (const widget of measurable) {
        lines.push(
            `    one(${JSON.stringify(widget.id)}, widgets.${rustFieldName(widget.id)}, ` +
                `${widget.x}, ${widget.y}, ${widget.width}, ${widget.height});`,
        );
    }
    lines.push('    problems');
    lines.push('}');
    lines.push('');

    // The event path: tap the designed centre of each widget that raises something, and check that an event
    // for *that* widget comes back. This is the question a flash and a finger would answer, answered here
    // instead -- whether the coordinates the canvas shows are the coordinates the widgets respond to.
    const withEvents = document.widgets.filter((widget) => widget.events.length > 0);
    lines.push('/// Taps the centre of every widget that raises an event, and checks what comes back.');
    lines.push('pub fn touch_checks<const N: usize, const E: usize, const D: usize>(');
    lines.push("    gui: &mut GuiContext<'_, N, E, D>,");
    lines.push('    widgets: &crate::screen::SimPanelWidgets,');
    lines.push(') -> Vec<String> {');
    lines.push('    /// A press and a release at one point, with the timing the crate needs to call it a click.');
    lines.push('    fn tap<const N: usize, const E: usize, const D: usize>(');
    lines.push("        gui: &mut GuiContext<'_, N, E, D>,");
    lines.push('        x: i32,');
    lines.push('        y: i32,');
    lines.push('    ) -> Vec<UiEvent> {');
    lines.push('        let _ = gui.handle_input(InputEvent::Pointer {');
    lines.push('            x,');
    lines.push('            y,');
    lines.push('            state: PointerState::Pressed,');
    lines.push('            button: PointerButton::Primary,');
    lines.push('        });');
    lines.push('        let _ = gui.tick_input(20);');
    lines.push('        let _ = gui.handle_input(InputEvent::Pointer {');
    lines.push('            x,');
    lines.push('            y,');
    lines.push('            state: PointerState::Released,');
    lines.push('            button: PointerButton::Primary,');
    lines.push('        });');
    lines.push('        let _ = gui.tick_input(20);');
    lines.push('        let mut events = Vec::new();');
    lines.push('        while let Some(event) = gui.pop_event() {');
    lines.push('            events.push(event);');
    lines.push('        }');
    lines.push('        events');
    lines.push('    }');
    lines.push('');
    lines.push('    let mut problems: Vec<String> = Vec::new();');
    for (const widget of withEvents) {
        const cx = widget.x + Math.floor(widget.width / 2);
        const cy = widget.y + Math.floor(widget.height / 2);
        lines.push('    {');
        lines.push(`        let events = tap(gui, ${cx}, ${cy});`);
        lines.push(
            `        let raised = events.iter().any(|event| matches!(event, ` +
                `UiEvent::Clicked(other) | UiEvent::ValueChanged(other) if *other == widgets.${rustFieldName(widget.id)}));`,
        );
        lines.push('        if !raised {');
        lines.push(
            `            problems.push(format!("${widget.id}: a tap at its designed centre (${cx}, ${cy}) raised ` +
                `nothing for it ({} events came back)", events.len()));`,
        );
        lines.push('        }');
        lines.push('    }');
    }
    const empty = fixture.empty ?? { x: 0, y: 0 };
    lines.push('    {');
    lines.push('        // Nothing is under this point, so nothing may claim it.');
    lines.push(`        let events = tap(gui, ${empty.x}, ${empty.y});`);
    lines.push('        let claimed = events');
    lines.push('            .iter()');
    lines.push('            .filter(|event| matches!(event, UiEvent::Clicked(_) | UiEvent::ValueChanged(_)))');
    lines.push('            .count();');
    lines.push('        if claimed != 0 {');
    lines.push(
        `            problems.push(format!("a tap at (${empty.x}, ${empty.y}), where no widget is, was claimed by ` +
            `{} widget event(s)", claimed));`,
    );
    lines.push('        }');
    lines.push('    }');
    lines.push('    problems');
    lines.push('}');
    lines.push('');
    return lines.join('\n');
}

/**
 * Writes the generated Rust side of a new project, so this crate can compile and drive it.
 *
 * The other checks here test the *crate*: that it lays the design out where the canvas said, and that a tap
 * reaches the widget. This one tests the code the extension generates -- `ui::Designer`'s press/release state
 * machine, its dispatch match and its render calls -- which is otherwise only ever proven to compile.
 *
 * The handlers are the test's own (a counter rather than a log line), which is also the point: `ui.rs` calls
 * its handlers *by name*, so a rename on either side stops this compiling.
 */
function writeDispatchHarness() {
    // The landscape CYD, which is the board with touch and therefore the generated API with a pointer in it.
    const document = starterDocument({ boardId: 'sunton-3248s035r', panelWidth: 320, panelHeight: 480, rotation: 3 });
    const canvas = designCanvasSize(document.panelWidth, document.panelHeight, document.rotation);
    const button = document.widgets.find((widget) => widget.id === 'go');
    const centreX = button.x + Math.floor(button.width / 2);
    const centreY = button.y + Math.floor(button.height / 2);

    fs.writeFileSync(path.join(SIM_DIR, 'src', 'ui.kdl'), emitStarterKdl(document));
    fs.writeFileSync(path.join(SIM_DIR, 'src', 'ui.rs'), emitUiRs(document, true));

    const lines = [];
    lines.push('// Generated by tests/tools/designer-sim.js. DO NOT EDIT.');
    lines.push('//');
    lines.push('// Where the starter design puts things, so the dispatch harness can tap them.');
    lines.push('');
    lines.push(`pub const CANVAS_W: u32 = ${canvas.width};`);
    lines.push(`pub const CANVAS_H: u32 = ${canvas.height};`);
    lines.push('/// The centre of the button the starter design places.');
    lines.push(`pub const BUTTON_X: i32 = ${centreX};`);
    lines.push(`pub const BUTTON_Y: i32 = ${centreY};`);
    lines.push('/// A point the starter design covers with nothing.');
    lines.push('pub const EMPTY_X: i32 = 2;');
    lines.push(`pub const EMPTY_Y: i32 = ${canvas.height - 2};`);
    lines.push('');
    fs.writeFileSync(path.join(SIM_DIR, 'src', 'starter_expectations.rs'), lines.join('\n'));
}

function main() {
    const args = process.argv.slice(2);
    const run = !args.includes('--no-run');

    const fixture = JSON.parse(fs.readFileSync(FIXTURE, 'utf8'));
    const document = documentFromFixture(fixture);
    const problems = validateDocument(document);
    if (problems.length > 0) {
        console.error(`the fixture is not a valid design: ${problems[0]}`);
        process.exit(1);
    }
    const kdl = emitKdl(document);

    fs.mkdirSync(path.dirname(SCREEN), { recursive: true });
    fs.writeFileSync(SCREEN, kdl);

    // The same design, fontless: the pixel difference between the two is what proves the font was applied
    // rather than quietly dropped, which is the failure the old `Font id` field had.
    const fontless = {
        ...document,
        fonts: [],
        // Only the widgets that *have* a font property are cleared: adding one to a rectangle would be an
        // unknown property, which is what validation said the first time this was written.
        widgets: document.widgets.map((widget) => {
            const props = { ...widget.props };
            if ('font' in props) {
                props.font = '';
            }
            if ('style' in props) {
                props.style = '';
            }
            // A property that travels *inside* the style expression is cleared the same way, or the widget would
            // look identical in both renders and the difference would be attributed to nothing.
            for (const property of widgetSpec(widget.tag)?.props ?? []) {
                if (property.viaStyle === true) {
                    props[property.name] = '';
                }
            }
            return { ...widget, props };
        }),
    };
    const fontlessProblems = validateDocument(fontless);
    if (fontlessProblems.length > 0) {
        console.error(`the fontless fixture is not valid: ${fontlessProblems[0]}`);
        process.exit(1);
    }
    fs.writeFileSync(SCREEN_NO_FONT, emitKdl(fontless));
    fs.writeFileSync(EXPECTATIONS, expectationSource(document, kdl, fixture));
    const canvas = designCanvasSize(document.panelWidth, document.panelHeight, document.rotation);
    const declared = declaredFontWidgets(document);
    const builtIn = document.widgets.filter(
        (widget) => typeof widget.props.font === 'string' && isBuiltInFont(widget.props.font),
    );
    const styled = document.widgets.filter(
        (widget) => typeof widget.props.style === 'string' && widget.props.style !== '',
    );
    const tinted = document.widgets.filter((widget) =>
        (widgetSpec(widget.tag)?.props ?? []).some(
            (property) => property.viaStyle === true && widget.props[property.name] !== '',
        ),
    );
    if (declared.length === 0 || builtIn.length === 0 || styled.length === 0 || tinted.length === 0) {
        throw new Error(
            'the fixture must show every appearance route: a font the screen declares, one the crate ships, ' +
                'and a base style, since each reaches the pixels by different markup',
        );
    }
    const described = [
        ...declared.map((widget) => [widget, `declared font ${JSON.stringify(widget.props.font)}`]),
        ...builtIn.map((widget) => [widget, `built-in font ${JSON.stringify(widget.props.font)}`]),
        ...styled.map((widget) => [widget, `style ${JSON.stringify(widget.props.style)}`]),
        ...tinted.map((widget) => [widget, `text colour ${JSON.stringify(widget.props.text_color)}`]),
    ];
    const rectList = described.map(
        ([widget, what]) =>
            `    // ${JSON.stringify(widget.id)} (${what})\n    (${widget.x}, ${widget.y}, ${widget.width}, ` +
            `${widget.height}),`,
    );
    fs.writeFileSync(
        path.join(SIM_DIR, 'src', 'font_diff_expectations.rs'),
        [
            '// Generated by tests/tools/designer-sim.js. DO NOT EDIT.',
            '',
            `pub const CANVAS_W: u32 = ${canvas.width};`,
            `pub const CANVAS_H: u32 = ${canvas.height};`,
            '/// Every widget the design gave an appearance to: the regions the two renders must disagree about.',
            '///',
            '/// Three routes, and they travel by different markup. A *declared* font is a BDF file the screen',
            '/// declares and a widget names with `font=`, which the crate reads for labels and carousels. A',
            '/// *built-in* one ships inside the crate and has no attribute at all, so it is asked for with a',
            '/// `style` expression. A *base style* gives an ordinary widget a look its own properties cannot,',
            '/// and a *text colour* on a label takes the same route. A build is the only thing that can prove',
            '/// any of them is honoured -- none of the four has an attribute the parser would read.',
            `pub const APPEARANCE_RECTS: [(i32, i32, u32, u32); ${described.length}] = [`,
            ...rectList,
            '];',
            '',
        ].join('\n'),
    );
    writeDispatchHarness();
    console.log(
        `wrote ${path.relative(repoRoot(), SCREEN)}, ${path.relative(repoRoot(), EXPECTATIONS)} and the ` +
            `dispatch harness (${DESIGNER_FILES.rust})`,
    );

    if (!run) {
        return;
    }

    fs.mkdirSync(CARGO_HOME, { recursive: true });
    const env = {
        ...process.env,
        CARGO_HOME,
        CARGO_TARGET_DIR: TARGET_DIR,
        TMPDIR: path.join(TARGET_DIR, 'tmp'),
        // The host build must not pick up the xtensa target from any generated project's config.
        RUSTFLAGS: '',
    };
    fs.mkdirSync(env.TMPDIR, { recursive: true });

    const mode = process.argv.includes('--touch')
        ? 'touch'
        : process.argv.includes('--dispatch')
          ? 'dispatch'
          : process.argv.includes('--font')
            ? 'font_diff'
            : 'designer-sim';
    const result = spawnSync('cargo', ['run', '--release', '--quiet', '--bin', mode], {
        cwd: SIM_DIR,
        env,
        stdio: 'inherit',
        timeout: 25 * 60 * 1000,
    });
    if (result.error) {
        console.error(`could not run cargo: ${result.error.message}`);
        process.exit(1);
    }
    process.exit(result.status ?? 1);
}

main();
