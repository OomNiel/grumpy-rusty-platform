'use strict';

/**
 * Backing up the project folder (asked 2026-10-05).
 *
 * The name, the stamp and the exclusion rule are pure, so they are pinned here; the copy itself is Node's
 * `fs.cpSync` and is exercised for real in `NOTES.md` §45 (a fake project with a `target/` full of junk).
 */

const { test, ok, equal, notOk, contains } = require('../../lib/harness');
const { compiled } = require('../../lib/harness');

const backup = compiled('project/backup');

test('a build folder is not part of a backup, and a file called target is', () => {
    // `target/` is tens of gigabytes of compiler output, regenerated by the next build; copying it would bury
    // the project and take minutes. `.git` is deliberately kept: it is the history, not an artifact.
    notOk(backup.shouldCopyEntry('target', true));
    notOk(backup.shouldCopyEntry('node_modules', true));
    notOk(backup.shouldCopyEntry('.dsh-worktrees', true));
    ok(backup.shouldCopyEntry('target', false), 'a *file* named target is the user’s own work');
    ok(backup.shouldCopyEntry('.git', true), 'the history comes along');
    ok(backup.shouldCopyEntry('src', true));
    ok(backup.shouldCopyEntry('Cargo.toml', false));
    ok(backup.shouldCopyEntry('', true));
});

test('the stamp sorts, and the folder name is the project plus the date', () => {
    const date = new Date(2026, 9, 5, 18, 4, 9);   // 2026-10-05 18:04:09, local time
    equal(backup.backupStamp(date), '2026-10-05_180409');
    equal(backup.backupFolderName('my-blinky-pico2w', date), 'my-blinky-pico2w-2026-10-05_180409');
    // Date first so two backups sort in the order they were taken.
    const earlier = backup.backupFolderName('p', new Date(2026, 9, 4, 9, 0, 0));
    const later = backup.backupFolderName('p', new Date(2026, 9, 5, 9, 0, 0));
    ok(earlier < later, `${earlier} sorts before ${later}`);
    // A name that would be illegal or invisible as a folder is cleaned rather than lived with.
    equal(backup.backupFolderName('a/b:c', date), 'a-b-c-2026-10-05_180409');
    equal(backup.backupFolderName('  ', date), 'project-2026-10-05_180409');
});

test('a backup never overwrites a backup', () => {
    const date = new Date(2026, 9, 5, 18, 4, 9);
    const first = backup.backupFolderName('proj', date, []);
    equal(first, 'proj-2026-10-05_180409');
    // Same second, second backup: it gets a suffix instead of silently replacing the first one.
    equal(backup.backupFolderName('proj', date, [first]), 'proj-2026-10-05_180409-2');
    equal(backup.backupFolderName('proj', date, [first, `${first}-2`]), 'proj-2026-10-05_180409-3');
});

test('the plan line says what will happen and what is left out', () => {
    const line = backup.backupPlanLine('/home/me/proj', '/home/me/proj-2026-10-05_180409');
    contains(line, 'proj-2026-10-05_180409');
    contains(line, '/home/me/proj-2026-10-05_180409', 'the full destination, not just its name');
    contains(line, 'target');
});

test('the control is in the section, declared, and runnable', () => {
    const controls = compiled('ui/controls');
    const commands = controls.visibleControls(false).map((c) => c.command);
    ok(commands.includes('rustyPlatform.backupProject'), 'the control is in the Controls section');
    const control = controls.PACKAGE_CONTROLS.find((c) => c.command === 'rustyPlatform.backupProject');
    ok(control && control.label && control.detail && control.tooltip && control.icon, 'fully described');
});
