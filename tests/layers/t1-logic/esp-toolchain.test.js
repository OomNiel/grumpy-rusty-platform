'use strict';

/**
 * The Espressif toolchain plan.
 *
 * Pure logic, so this layer never touches a real toolchain: what is missing, in what order it
 * gets installed, and how espup's export file is turned into an environment. The detection that
 * feeds it is exercised by the t2 layer with fake `espup` / `espflash` executables.
 */

const { test, ok, equal, notOk, contains } = require('../../lib/harness');
const { compiled } = require('../../lib/harness');
const {
    chipsForTargets,
    missingEspPieces,
    espToolchainReady,
    espInstallCommands,
    espInstallCommandLine,
    parseToolchainList,
    parseExportEsp,
    withExportEspEnv,
    espToolchainSummary,
    ESP_TOOLCHAIN_NAME,
} = compiled('toolchain/espToolchain');

/** A machine where everything is installed. */
function complete(overrides = {}) {
    return {
        espup: { found: true, version: '0.18.0' },
        espflash: { found: true, version: '4.6.0' },
        toolchainInstalled: true,
        exportFile: '/home/grumpy/export-esp.sh',
        chips: ['esp32', 'esp32s3'],
        ...overrides,
    };
}

test('the chips to install come from the target triples', () => {
    equal(chipsForTargets(['xtensa-esp32-none-elf', 'xtensa-esp32s3-none-elf']), ['esp32', 'esp32s3']);
    // Arm triples are rustup's business and must not leak into an espup command.
    equal(chipsForTargets(['thumbv6m-none-eabi', 'xtensa-esp32s3-none-elf']), ['esp32s3']);
    equal(chipsForTargets(['xtensa-esp32s3-none-elf', 'xtensa-esp32-none-elf']), ['esp32', 'esp32s3']);
    equal(chipsForTargets([]), []);
});

test('a complete machine is ready, and says which pieces are missing otherwise', () => {
    equal(espToolchainReady(complete()), true);
    equal(missingEspPieces(complete()), []);

    // Order matters for the reader: install espup, then the toolchain, then espflash.
    equal(
        missingEspPieces(
            complete({
                espup: { found: false },
                toolchainInstalled: false,
                exportFile: undefined,
                espflash: { found: false },
            }),
        ),
        ['espup', 'toolchain', 'export-esp.sh', 'espflash'],
    );
});

test('the install plan is ordered and only contains what is missing', () => {
    const bare = complete({
        espup: { found: false },
        toolchainInstalled: false,
        exportFile: undefined,
        espflash: { found: false },
    });
    const steps = espInstallCommands(bare, ['esp32', 'esp32s3']);
    equal(
        steps.map((step) => step.id),
        ['espup', 'toolchain', 'espflash'],
    );
    equal(steps[0].command, 'cargo install espup --locked');
    equal(steps[1].command, 'espup install --targets esp32,esp32s3');
    equal(steps[2].command, 'cargo install espflash --locked');
    for (const step of steps) {
        ok(step.label.length > 0, `${step.id} needs a label`);
        ok(step.detail.length > 10, `${step.id} needs a line explaining what it does`);
    }
});

test('an installed piece is not reinstalled', () => {
    // The common case after a first project: espup is there, espflash is not.
    const steps = espInstallCommands(complete({ espflash: { found: false } }), ['esp32']);
    equal(steps.map((step) => step.id), ['espflash']);

    equal(espInstallCommands(complete(), ['esp32']), [], 'a ready machine needs no steps');
});

test('the targets fall back to both chips when none are given', () => {
    const bare = complete({ toolchainInstalled: false, exportFile: undefined });
    const steps = espInstallCommands(bare, []);
    contains(steps[0].command, '--targets esp32,esp32s3');
});

test('the steps become one shell line, so the terminal shows what happened', () => {
    const steps = espInstallCommands(
        complete({ espup: { found: false }, toolchainInstalled: false, exportFile: undefined }),
        ['esp32'],
    );
    equal(
        espInstallCommandLine(steps),
        'cargo install espup --locked && espup install --targets esp32',
    );
});

test('the espup toolchain is recognised in rustup\'s list', () => {
    equal(ESP_TOOLCHAIN_NAME, 'esp');
    ok(parseToolchainList('stable-x86_64-unknown-linux-gnu (default)\nesp\n'));
    ok(parseToolchainList('esp\n'), 'espup lists the toolchain by the name it was given');
    ok(parseToolchainList('esp-1.99.0.0\n'), 'a versioned name counts too');
    notOk(parseToolchainList('stable-x86_64-unknown-linux-gnu (default)\n'));
    notOk(parseToolchainList(''));
    notOk(parseToolchainList('espressif\n'), 'a prefix match has to be on a separator');
});

test("espup's export file is read, not sourced", () => {
    const content = [
        '# Xtensa toolchain, generated by espup',
        'export PATH="$HOME/.rustup/toolchains/esp/xtensa-esp32-elf-clang/xtensa-esp-elf/bin:$PATH"',
        'export LIBCLANG_PATH="$HOME/.rustup/toolchains/esp/xtensa-esp-elf/lib"',
        'export PATH="$HOME/.cargo/bin:$PATH"',
        '',
    ].join('\n');

    const parsed = parseExportEsp(content, '/home/grumpy');
    equal(parsed.vars.LIBCLANG_PATH, '/home/grumpy/.rustup/toolchains/esp/xtensa-esp-elf/lib');
    equal(parsed.pathPrepend, [
        '/home/grumpy/.rustup/toolchains/esp/xtensa-esp32-elf-clang/xtensa-esp-elf/bin',
        '/home/grumpy/.cargo/bin',
    ]);
    notOk(
        parsed.pathPrepend.some((entry) => entry.includes('$PATH')),
        'the $PATH placeholder is not a directory',
    );
});

test('the export file tolerates what a shell script really contains', () => {
    const content = [
        '# comment with an = sign',
        'PATH_WITHOUT_EXPORT=/somewhere',
        "export QUOTED='single'",
        'export NO_QUOTES=/plain',
        'export EMPTY=',
        'export LANGS=$HOME/a:$HOME/b',
    ].join('\n');

    const parsed = parseExportEsp(content, '/home/x');
    equal(parsed.vars.QUOTED, 'single');
    equal(parsed.vars.NO_QUOTES, '/plain');
    equal(parsed.vars.EMPTY, '');
    equal(parsed.vars.LANGS, '/home/x/a:/home/x/b');
    notOk('PATH_WITHOUT_EXPORT' in parsed.vars, 'only `export` lines define variables');
    equal(parsed.pathPrepend, []);
});

test('the exported environment is prepended to PATH, never replaces it', () => {
    const parsed = parseExportEsp(
        'export PATH="/opt/xtensa/bin:$PATH"\nexport LIBCLANG_PATH=/opt/xtensa/lib\n',
        '/home/x',
    );
    const environment = withExportEspEnv({ PATH: '/usr/bin:/bin', HOME: '/home/x' }, parsed);
    equal(environment.PATH, '/opt/xtensa/bin:/usr/bin:/bin', 'the Espressif linker has to win');
    equal(environment.LIBCLANG_PATH, '/opt/xtensa/lib');
    equal(environment.HOME, '/home/x', 'the rest of the environment is untouched');
});

test('an empty PATH does not leave a stray separator', () => {
    const parsed = parseExportEsp('export PATH="/opt/x/bin:$PATH"\n', '/home/x');
    equal(withExportEspEnv({}, parsed).PATH, '/opt/x/bin');
});

test('the summary says what is missing, or which versions are in place', () => {
    equal(espToolchainSummary(complete()), 'ready (0.18.0, 4.6.0)');
    contains(espToolchainSummary(complete({ espflash: { found: false } })), 'missing: espflash');

    const unknownVersions = complete({ espup: { found: true }, espflash: { found: true } });
    equal(espToolchainSummary(unknownVersions), 'ready');
});
