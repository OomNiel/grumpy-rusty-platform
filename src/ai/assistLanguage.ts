/**
 * The assist's language: what it is told to be, and which answers it may offer back.
 *
 * The AI half of this extension was written for Rust and said so in three places: the system prompt ("a precise
 * Rust coding assistant … Embassy"), the code fence it reads back (`rustCodeBlocks`), and the project facts it
 * sends (Cargo dependencies). A C++ project has none of those things -- it is an Arduino sketch with an LVGL 9
 * screen -- and an assistant told it is looking at Rust gives confident answers about the wrong language.
 *
 * So the words live here, chosen by language: one module the chat can consult, no `vscode` import, and every
 * sentence pinned by the suite rather than by reading a prompt in a screenshot. The rules that do *not* change
 * between the two -- never invent a pin, a crate or an API; show the code -- are stated once and inherited.
 */

/** The two languages a project of ours can be written in. */
export type AssistLanguage = 'rust' | 'cpp';

/**
 * The language of a document the prompt block and the `//~` trigger work in.
 *
 * `ino` is Arduino's own id and `arduino` is what some builds report; both are C++ as far as the assist is
 * concerned. Anything else is `undefined`, which is how a flow says "not mine" without naming languages itself.
 */
export function assistLanguageOfDocument(languageId: string): AssistLanguage | undefined {
    switch (languageId) {
        case 'rust':
            return 'rust';
        case 'cpp':
        case 'c':
        case 'ino':
        case 'arduino':
            return 'cpp';
        default:
            return undefined;
    }
}

/**
 * The language of a project, from the backend that owns it.
 *
 * A project with no marker at all answers "rust", which is every project that existed before the Arduino backend
 * and every project whose marker this build cannot read.
 */
export function assistLanguageOfProject(language: string | undefined): AssistLanguage {
    return language === 'arduino' ? 'cpp' : 'rust';
}

/** The info string a code fence needs for this language, which is also what the guard below reads back. */
export function codeFenceFor(language: AssistLanguage): string {
    return language === 'cpp' ? 'cpp' : 'rust';
}

/**
 * The system message for a free-form question.
 *
 * Everything true of both languages is stated once; what differs is the framework, the project's own files and
 * the instruction about generating code. The C++ half names `src/ui.cpp` on purpose: a model that "helpfully"
 * rewrites a generated file produces a change the Designer overwrites on the next save, which is the most
 * confusing possible outcome of a good answer.
 */
export function chatSystemPrompt(language: AssistLanguage): string {
    if (language === 'cpp') {
        return (
            'You are a precise C++ coding assistant for embedded firmware: Arduino sketches (C++17) built with ' +
            '`arduino-cli` for RP2040/RP2350 and ESP32 boards, drawing their user interface with LVGL 9 on a ' +
            'small SPI panel. Answer in short, concrete C++. Never invent a pin, a library or an API that is not ' +
            'in the context below; if something is missing, say what is missing. Prefer showing the code to ' +
            'describing it.\n\n' +
            // The project's own rules, because a model cannot read them off the files it can see.
            'The project\'s rules: `src/ui.cpp` and `src/ui.h` are generated by the Designer and rewritten on ' +
            'every save, so a person\'s code belongs in `src/ui_handlers.cpp`; `src/panel.cpp` is generated ' +
            'from the Hardware panel and holds the pins and the MADCTL rotation. Nothing is allocated after ' +
            '`setup()`, there is no STL container in the firmware, logging is `Serial.printf`, and `loop()` ' +
            'returns to the framework rather than blocking in `delay()`. The only library the sketch uses is ' +
            'LVGL; the cores are the `rp2040` and `esp32` Arduino packages.\n\n' +
            // Same shape rule as the Rust half, in this language's words: a whole item replaces the real one.
            'When asked to change code, return ONLY the item that changes -- the one function, method or ' +
            'struct -- and leave every other item out of your answer entirely. "Only the item" means that item ' +
            'WHOLE: reproduce every line of it, including the lines you did not change, because the item ' +
            'replaces the real one and a function that arrives carrying only the changed lines deletes the ' +
            'rest. Do not return the whole file unless the developer asks for the whole file. Never write ' +
            '`...`, `// ...` or any other placeholder for code you did not write: if something is too long to ' +
            'include, say so in a sentence instead of guessing. Never reproduce a file from the context to ' +
            '"keep it unchanged" -- leaving it out is how it stays unchanged. Keep the signatures and the names ' +
            'as they are, and put nothing at file scope that the item does not need.'
        );
    }
    return (
        'You are a precise Rust coding assistant for embedded, often `no_std`, firmware built on the ' +
        'Embassy async framework. Answer in short, concrete Rust. Never invent a crate, a pin or an API that ' +
        'is not in the context below; if something is missing, say what is missing. Prefer showing the code to ' +
        'describing it.\n\n' +
        // The shape of the answer, spelled out because the shape is what decides whether applying it is safe.
        // A model that answers "add this to the loop" with a reconstructed whole file deletes everything it did
        // not feel like reproducing (2026-10-12), and a placeholder is the same mistake with a comment on it.
        'When asked to change code, return ONLY the item that changes -- the one `fn`, `impl` or `struct` -- ' +
        'and leave every other item out of your answer entirely. "Only the item" means that item WHOLE: ' +
        'reproduce every line of it, including the lines you did not change, because the item replaces the ' +
        'real one and a function that arrives carrying only the changed lines deletes the rest. Do not ' +
        'return the whole file unless the developer asks for the whole file. Never write `...`, ' +
        '`// ...` or any other placeholder for code you did not write: if something is too long to include, ' +
        'say so in a sentence instead of guessing. Never reproduce a file from the context to "keep it ' +
        'unchanged" -- leaving it out is how it stays unchanged. Keep the file\'s own attributes, signature ' +
        'and names as they are; put any `use` a new path needs inside the function body, which is legal Rust.'
    );
}

/** The facts a sketch's prompts carry, gathered by the caller so this module stays free of `vscode`. */
export interface SketchFacts {
    /** The board's own name, e.g. `Raspberry Pi Pico 2 W`. */
    board?: string;
    /** Which silicon family, when it is known: the two have different RAM and different cores. */
    kind?: 'rp' | 'esp';
    /** Whether the Designer owns the screen, which decides whether `ui.cpp` exists at all. */
    designer?: boolean;
}

/**
 * The C++ project brief, in the place the Cargo dependency list occupies for Rust.
 *
 * It says what the project *is* rather than what it contains, because a sketch has almost nothing to list: one
 * `.ino`, three generated files and whatever handlers the person wrote. What a small model cannot guess is that
 * `ui.cpp` is generated, and getting that wrong is what makes an otherwise correct answer unusable.
 */
export function sketchBrief(facts: SketchFacts): string {
    const board = facts.board ?? 'an RP2040 or ESP32 board';
    const family =
        facts.kind === 'rp'
            ? 'RP2040/RP2350 (Arm Cortex-M0+, no floating-point unit on the M0+, 264 KB of RAM)'
            : facts.kind === 'esp'
                ? 'ESP32 (dual core, far more RAM than an RP2040, the same LVGL code)'
                : 'an RP2040 or ESP32';
    const lines = [
        `This is an Arduino sketch for ${board}, ${family}, built with \`arduino-cli\`.`,
        'The files: the `.ino` holds `setup()` and `loop()`; `src/panel.cpp` drives the panel (pins, init, ' +
        'rotation); `src/ui_handlers.cpp` is where the person writes their code.',
    ];
    if (facts.designer === true) {
        lines.push(
            'src/ui.cpp and src/ui.h are generated from the Designer\'s document and rewritten on every save: ' +
            'they are not edited by hand, and a change to them is lost.',
        );
    } else {
        lines.push('src/ui.cpp and src/ui.h, when they exist, are generated by the Designer and not edited by hand.');
    }
    lines.push('The display is LVGL 9. The project takes no other library.');
    return lines.join('\n');
}

/**
 * Is this fenced block an answer in this language?
 *
 * A block with no info string counts either way: the assistant answers about the project in front of it, and a
 * model that omits the language is still writing that project's language. A block that *named* another language
 * is left alone -- offering to paste a Python listing into a firmware file is worse than offering nothing.
 */
export function isCodeBlockFor(language: AssistLanguage, block: { language: string }): boolean {
    const named = block.language.trim().toLowerCase();
    if (named === '') {
        return true;
    }
    if (language === 'cpp') {
        return /^(c\+\+|cpp|c|cc|cxx|h|hpp|ino|arduino)$/.test(named);
    }
    return /^(rust|rs|rust-lang)$/.test(named);
}

/** The words a `//~` line may name in a C++ project. Kept as a list so the hint text and the reader agree. */
export const CPP_ASSIST_KEYWORDS: readonly string[] = ['struct', 'class', 'switch', 'for', 'while', 'if', 'fn', 'lvgl'];

/**
 * The C++ example set for type `//~ keyword` in a `.cpp` or `.ino` file.
 *
 * Same shape as the Rust set: a few variations of one construct, short enough to read in the chat and to leave
 * in the file as a starting point. `lvgl` is the one that is not a C++ keyword -- it is the thing a person
 * writing a screen actually asks for, and the four calls below are the ones every LVGL widget starts with.
 */
export function cppAssistExamples(keyword: string): string {
    const word = keyword.trim().toLowerCase();
    if (word === 'struct') {
        return [
            'Struct variations:',
            '```cpp',
            '// a plain struct',
            'struct Point {',
            '    int16_t x;',
            '    int16_t y;',
            '};',
            '',
            '// with a default member initialiser',
            'struct Reading {',
            '    float temperature = 0.0f;',
            '    bool valid = false;',
            '};',
            '',
            '// with a constructor',
            'struct Colour {',
            '    uint8_t r, g, b;',
            '    Colour(uint8_t r, uint8_t g, uint8_t b) : r(r), g(g), b(b) {}',
            '};',
            '',
            '// an aggregate built in place (no allocation)',
            'Point origin{0, 0};',
            '```',
        ].join('\n');
    }
    if (word === 'class') {
        return [
            'Class variations:',
            '```cpp',
            '// a class with a public method and private state',
            'class Counter {',
            '  public:',
            '    void add(int amount) { count_ += amount; }',
            '    int count() const { return count_; }',
            '',
            '  private:',
            '    int count_ = 0;',
            '};',
            '',
            '// a class with a constructor and a static factory',
            'class Debounce {',
            '  public:',
            '    explicit Debounce(uint32_t ms) : ms_(ms) {}',
            '    bool update(bool raw) { /* ... */ return raw; }',
            '',
            '  private:',
            '    uint32_t ms_;',
            '    uint32_t last_ = 0;',
            '};',
            '```',
        ].join('\n');
    }
    if (word === 'switch') {
        return [
            'Switch variations:',
            '```cpp',
            '// a statement switch',
            'switch (state) {',
            '    case State::Idle:',
            '        break;',
            '    case State::Running:',
            '        run();',
            '        break;',
            '    default:',
            '        break;',
            '}',
            '',
            '// several labels for one arm',
            'switch (key) {',
            '    case \'a\':',
            '    case \'A\':',
            '        handle_a();',
            '        break;',
            '    default:',
            '        break;',
            '}',
            '```',
        ].join('\n');
    }
    if (word === 'for') {
        return [
            'For loop variations:',
            '```cpp',
            '// counting up',
            'for (int i = 0; i < 10; i += 1) {',
            '    // work',
            '}',
            '',
            '// counting down',
            'for (int i = 9; i >= 0; i -= 1) {',
            '    // work',
            '}',
            '',
            '// over a fixed array (no allocation)',
            'for (size_t i = 0; i < sizeof(values) / sizeof(values[0]); i += 1) {',
            '    use(values[i]);',
            '}',
            '',
            '// range-for, when the size is known at compile time',
            'for (const auto &value : values) {',
            '    use(value);',
            '}',
            '```',
        ].join('\n');
    }
    if (word === 'while') {
        return [
            'While loop variations:',
            '```cpp',
            '// a plain while',
            'while (!ready()) {',
            '    // work',
            '}',
            '',
            '// do/while: the body runs once before the test',
            'do {',
            '    // work',
            '} while (more());',
            '',
            '// a bounded wait that never blocks forever',
            'const uint32_t deadline = millis() + 500;',
            'while (!ready() && static_cast<int32_t>(millis() - deadline) < 0) {',
            '    // work',
            '}',
            '```',
        ].join('\n');
    }
    if (word === 'if') {
        return [
            'If variations:',
            '```cpp',
            '// simple if',
            'if (condition) {',
            '    // work',
            '}',
            '',
            '// if / else',
            'if (condition) {',
            '    // work',
            '} else {',
            '    // otherwise',
            '}',
            '',
            '// else-if chain',
            'if (a) {',
            '    // a',
            '} else if (b) {',
            '    // b',
            '} else {',
            '    // neither',
            '}',
            '',
            '// a guard clause, which reads better inside a function',
            'if (!ready()) return;',
            '```',
        ].join('\n');
    }
    if (word === 'fn') {
        return [
            'Function variations:',
            '```cpp',
            '// a free function',
            'int add(int a, int b) {',
            '    return a + b;',
            '}',
            '',
            '// a function that takes its argument by reference',
            'void fill(Reading &reading, float value) {',
            '    reading.temperature = value;',
            '    reading.valid = true;',
            '}',
            '',
            '// a function that takes a string literal without copying',
            'void show(const char *text) {',
            '    lv_label_set_text(label_status, text);',
            '}',
            '',
            '// a static helper nothing outside this file can see',
            'static uint16_t clamp16(int32_t value) {',
            '    if (value < 0) return 0;',
            '    if (value > 65535) return 65535;',
            '    return static_cast<uint16_t>(value);',
            '}',
            '```',
        ].join('\n');
    }
    if (word === 'lvgl') {
        return [
            'LVGL 9: the four calls every widget starts with, and the ones a screen needs:',
            '```cpp',
            '// create, place, size',
            'lv_obj_t *label = lv_label_create(lv_screen_active());',
            'lv_obj_set_pos(label, 8, 8);',
            'lv_obj_set_size(label, 120, 20);',
            'lv_label_set_text(label, "hello");',
            '',
            '// a style on one object only (selector 0, part MAIN)',
            'lv_obj_set_style_text_color(label, lv_color_hex(0xFFFFFF), 0);',
            'lv_obj_set_style_bg_opa(label, LV_OPA_TRANSP, 0);',
            '',
            '// a callback: the handler receives the object that fired',
            'lv_obj_add_event_cb(button, on_button_clicked, LV_EVENT_CLICKED, nullptr);',
            '',
            '// drive it from loop(): no while(true), no delay()',
            'void loop() {',
            '    lv_timer_handler();',
            '    delay(5);',
            '}',
            '```',
        ].join('\n');
    }
    return `No examples yet for keyword "${keyword}". In a sketch the useful ones are: ${CPP_ASSIST_KEYWORDS.join(', ')}.`;
}
