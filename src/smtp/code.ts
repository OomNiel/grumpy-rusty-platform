/**
 * The code the SMTP wizard writes into a project, as pure text.
 *
 * The module it produces, `src/smtp.rs`, is a self-contained ESP32 task: it brings the radio up
 * (word-for-word the same bring-up `src/net.rs` uses for the clock, so the half that is easy to get
 * wrong is borrowed from code that already compiles), then opens a TCP socket to the relay and sends
 * the keep-alive posts the wizard asked for. Credentials are read with `option_env!` -- the same
 * contract the Wi-Fi templates honour -- so the password never lands in the project tree; only the
 * per-project post configuration (from, subscriptions, cadence, subject, body) is baked in.
 *
 * This file is `vscode`-free so t1 can pin the generated text and the file-editing helpers without
 * spinning up an extension host.
 */

import { execFileSync } from 'node:child_process';
import { applyDependency, parseCargoToml, findDependency } from '../library/cargoToml';
import { ensureFeatureDefinition, setFeatureInDefault } from '../designer/features';
import type { SmtpPosts } from './credentials';

/**
 * Pass the generated Rust through `rustfmt` so the file the wizard writes is canonical -- the
 * template only has to be *correct*, not pre-formatted for every input length.
 *
 * Best-effort and `vscode`-free so t1 can still pin it: when `rustfmt` is not on PATH (or rejects the
 * source) the text is returned untouched. The wizard always writes a file, and a project that runs
 * `cargo build` with rustfmt in its toolchain will format it there; the goal is that *this*
 * extension ships rustfmt-clean firmware so a `rustfmt --check` against the written `smtp.rs` is
 * green out of the gate.
 */
export function formatSmtpRs(source: string): string {
    try {
        return execFileSync('rustfmt', ['--edition', '2021', '--emit', 'stdout'], {
            input: source,
            encoding: 'utf8',
            timeout: 10_000,
        }) as string;
    } catch {
        return source;
    }
}

/** A recipient list rendered as a Rust `&[&str]` literal, one per line for readability. */
function subscriptionsLiteral(subscriptions: readonly string[]): string {
    if (subscriptions.length === 0) {
        return '&[]';
    }
    const items = subscriptions.map((address) => `    "${address.trim()}",`).join('\n');
    return `&[\n${items}\n]`;
}

/**
 * The generated `src/smtp.rs`: the ESP32 task that owns the radio.
 *
 * The Wi-Fi bring-up is copied from `net.rs`'s clock task so the radio plumbing is known-good, and so is
 * its SNTP query: `peripherals.WIFI` can be moved once per boot, so this one task does the clock's time
 * query *and* the keep-alive posts rather than two tasks competing for the peripheral. The time it finds
 * is published through `crate::net::SYNCED_TIME`, which main.rs already reads into the RTC. The SMTP
 * dialogue is plain TCP (`embassy_net::tcp::TcpSocket`) with a hand-rolled base64 for `AUTH LOGIN` and no
 * allocation.
 *
 * TLS is not wired here -- a no_std TLS stack is the only missing piece and the firmware already has
 * an allocator to back one. With `SMTP_USE_STARTTLS` set the module logs a warning and sends in the
 * clear on a LAN; adding a handshake later is a localized change.
 *
 * Every line terminator is spelled as `CRLF` (a `[13, 10]` const) rather than `\r\n` so the text is
 * built without C-style escapes.
 */
export function emitSmtpRs(posts: SmtpPosts): string {
    const from = posts.from.trim();
    const subject = posts.keepaliveSubject || 'I am still here';
    const body = posts.keepaliveBody || 'This device is powered on and connected to the network.';
    const minutes = posts.keepaliveMinutes || 15;
    const subscriptions = subscriptionsLiteral(posts.subscriptions);

    return `// Generated by Grumpy's Rusty Platform for VS Code. Editable once written: this is your
// firmware, not a scaffold.
//
// An SMTP client over Wi-Fi, in the one task that owns the radio. peripherals.WIFI can be moved
// once per boot, so this task does both radio jobs: it asks the network for the time when the design
// needed one (publishing it through net.rs's own signal, exactly as the clock task does), and then
// opens a TCP socket to the relay reported by SMTP_HOST and sends the keep-alive posts this wizard
// configured. Credentials are read at *compile* time with option_env!, so none of them live in your
// source tree -- set them on the build command instead:
//
//   SMTP_HOST="mail.example.com" SMTP_PASSWORD="..." cargo run --release
//
// The Wi-Fi credentials this needs are the same ones the clock uses (WIFI_SSID / WIFI_PASSWORD),
// which Flash and Debug already asks for and remembers.
//
// TLS is not yet wired: a no_std TLS stack is the only missing piece and the firmware already has an
// allocator to back one. With SMTP_USE_STARTTLS set this module logs a warning and sends in the clear
// on a LAN -- flip a constant and add the handshake once the stack is present.

use embassy_executor::Spawner;
use embassy_net::dns::DnsQueryType;
use embassy_net::tcp::TcpSocket;
use embassy_net::udp::{PacketMetadata, UdpSocket};
use embassy_net::{Config as NetConfig, Runner, StackResources};
use embassy_time::{with_timeout, Duration, Timer};
use embedded_io_async::Write;
use esp_hal::peripherals::WIFI;
use esp_hal::rng::Rng;
use esp_radio::wifi::sta::StationConfig;
use esp_radio::wifi::{
    AuthenticationMethodConfig, Config as WifiConfig, ControllerConfig, Interface, WifiController,
};

/// CR LF -- the terminator of every line in an SMTP dialogue.
const CRLF: &[u8] = &[13, 10];

/// The Wi-Fi credentials this client joins the network with. Same contract as net.rs: read at
/// compile time, never in the source tree.
const WIFI_SSID: &str = match option_env!("WIFI_SSID") {
    Some(value) => value,
    None => "YOUR_WIFI_SSID",
};
const WIFI_PASSWORD: &str = match option_env!("WIFI_PASSWORD") {
    Some(value) => value,
    None => "YOUR_WIFI_PASSWORD",
};

/// The time server, the same one net.rs asks. pool.ntp.org resolves to a nearby server.
const NTP_SERVER: &str = "pool.ntp.org";

/// Minutes to add to UTC to get the time on the glass. Written into .cargo/esp-config.toml by the
/// wizard; the clock task in net.rs reads the same variable, so the two agree by construction.
fn tz_offset_minutes() -> i64 {
    match option_env!("TZ_OFFSET_MINUTES") {
        Some(value) => value.trim().parse().unwrap_or(0),
        None => 0,
    }
}

/// Where the mail goes. Set on the build command, like the Wi-Fi credentials.
const SMTP_HOST: &str = match option_env!("SMTP_HOST") {
    Some(value) => value,
    None => "",
};
/// Parse a base-10 \`u16\` at compile time. \`str::parse\` is not const-stable, so the port is parsed
/// by hand: this keeps \`SMTP_PORT\` a true \`const\` with no nightly feature gates.
const fn parse_port(bytes: &[u8]) -> Option<u16> {
    if bytes.is_empty() {
        return None;
    }
    let mut n: u16 = 0;
    let mut i = 0usize;
    while i < bytes.len() {
        let digit: u16 = match bytes[i] {
            b'0' => 0,
            b'1' => 1,
            b'2' => 2,
            b'3' => 3,
            b'4' => 4,
            b'5' => 5,
            b'6' => 6,
            b'7' => 7,
            b'8' => 8,
            b'9' => 9,
            _ => return None,
        };
        n = match n.checked_mul(10) {
            Some(m) => match m.checked_add(digit) {
                Some(v) => v,
                None => return None,
            },
            None => return None,
        };
        i += 1;
    }
    Some(n)
}

const SMTP_PORT: u16 = match option_env!("SMTP_PORT") {
    Some(value) => match parse_port(value.as_bytes()) {
        Some(port) => port,
        None => 25,
    },
    None => 25,
};
const SMTP_USERNAME: &str = match option_env!("SMTP_USERNAME") {
    Some(value) => value,
    None => "",
};
const SMTP_PASSWORD: &str = match option_env!("SMTP_PASSWORD") {
    Some(value) => value,
    None => "",
};
/// Compare two byte strings at compile time. \`str\` equality is not const-stable, so the value of an
/// env-var flag is compared byte-by-byte to keep the constant \`const\`.
const fn bytes_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0usize;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// Present only when the build set SMTP_USE_STARTTLS to "1"; anything else is plain.
const SMTP_USE_STARTTLS: bool = match option_env!("SMTP_USE_STARTTLS") {
    Some(value) => bytes_eq(value.as_bytes(), b"1"),
    None => false,
};

/// The per-project post configuration the wizard wrote into this source file.
const SMTP_FROM: &str = "${from}";
const SMTP_SUBSCRIPTIONS: &[&str] = ${subscriptions};
const SMTP_KEEPALIVE_MINUTES: u64 = ${minutes};
const SMTP_KEEPALIVE_SUBJECT: &str = "${subject}";
const SMTP_KEEPALIVE_BODY: &str = "${body}";

/// The stack's buffer pool has to outlive the task, so it is a static. It is written once: the task
/// is spawned at most once per boot.
static SMTP_STACK_RESOURCES: static_cell::StaticCell<StackResources<3>> = static_cell::StaticCell::new();

/// The one radio task: joins the network, answers the clock's time query when wants_time, then sends
/// a keep-alive post on a timer until reset.
///
/// wants_time is ui::HAS_CLOCK && needs_time from main.rs: a design with a clock whose RTC has never
/// been set. The query happens here rather than in net.rs because only one task can own the peripheral,
/// and this is the one main.rs spawns when the SMTP feature is on.
#[embassy_executor::task]
pub async fn smtp_task(wifi: WIFI<'static>, wants_time: bool) {
    // Open and protected networks are configured differently: WPA2 with an empty key never
    // associates, and an open network rejects a key that was supplied. This is copied from net.rs.
    let authentication = if WIFI_PASSWORD.is_empty() {
        AuthenticationMethodConfig::Open
    } else {
        AuthenticationMethodConfig::WpaWpa2Personal(
            WIFI_PASSWORD
                .try_into()
                .expect("the password is longer than 64 bytes"),
        )
    };
    let station_config = WifiConfig::Station(
        StationConfig::default()
            .with_ssid(WIFI_SSID.try_into().expect("the network name is longer than 32 bytes"))
            .with_authentication(authentication),
    );
    let interface = Interface::station();
    let mut controller = match WifiController::new(
        wifi,
        ControllerConfig::default().with_initial_config(station_config),
    ) {
        Ok(controller) => controller,
        Err(error) => {
            log::warn!("smtp: Wi-Fi refuses to start ({:?})", error);
            return;
        }
    };

    let mut joined = false;
    for attempt in 1..=5u32 {
        log::info!("smtp: joining {} (attempt {})", WIFI_SSID, attempt);
        match controller.connect_async().await {
            Ok(_) => {
                joined = true;
                break;
            }
            Err(error) => {
                log::warn!("smtp: association failed: {:?}", error);
                Timer::after(Duration::from_secs(5)).await;
            }
        }
    }
    if !joined {
        log::warn!("smtp: no network; keep-alive posts will not be sent");
        return;
    }

    let rng = Rng::new();
    let seed = (rng.random() as u64) << 32 | rng.random() as u64;
    let (stack, runner) = embassy_net::new(
        interface,
        NetConfig::dhcpv4(Default::default()),
        SMTP_STACK_RESOURCES.uninit().write(StackResources::<3>::new()),
        seed,
    );
    let spawner = unsafe { Spawner::for_current_executor().await };
    spawner.spawn(smtp_net_task(runner).expect("the network stack task is spawned exactly once"));
    if with_timeout(Duration::from_secs(30), stack.wait_config_up())
        .await
        .is_err()
    {
        log::warn!("smtp: no address from DHCP; keep-alive posts will not be sent");
        return;
    }
    match stack.config_v4() {
        Some(config) => log::info!("smtp: network up at {}", config.address),
        None => return,
    }

    // The clock's half of this task. Publishing through net.rs's signal is what main.rs already reads:
    // the value is put in the RTC only while the RTC has never been set, so a boot that did not need
    // the time simply drops it.
    if wants_time {
        for attempt in 1..=3u32 {
            if let Some((hour, minute, second)) = ntp_time(stack).await {
                log::info!(
                    "clock: the network says {:02}:{:02}:{:02} (attempt {})",
                    hour,
                    minute,
                    second,
                    attempt
                );
                crate::net::SYNCED_TIME.signal((hour, minute, second));
                break;
            }
            log::warn!("clock: no answer from the time server (attempt {})", attempt);
            Timer::after(Duration::from_secs(2)).await;
        }
    }

    if SMTP_USE_STARTTLS {
        log::warn!("smtp: SMTP_USE_STARTTLS is set, but this build sends in the clear (no TLS stack)");
    }
    if SMTP_HOST.is_empty() {
        log::warn!("smtp: SMTP_HOST is empty; keep-alive posts will not be sent");
        return;
    }

    log::info!("smtp: keep-alive posts every {} minute(s)", SMTP_KEEPALIVE_MINUTES);
    loop {
        Timer::after(Duration::from_secs(SMTP_KEEPALIVE_MINUTES * 60)).await;
        match smtp_post(stack).await {
            Ok(()) => log::info!("smtp: keep-alive post sent"),
            Err(error) => log::warn!("smtp: keep-alive post failed: {:?}", error),
        }
    }
}

/// Drives the stack; no packet moves while this task is not being polled.
#[embassy_executor::task]
async fn smtp_net_task(mut runner: Runner<'static, Interface>) {
    runner.run().await;
}

/// One keep-alive post: dial the relay, authenticate, and DATA the message to each subscription.
async fn smtp_post(stack: embassy_net::Stack<'static>) -> Result<(), SmtpError> {
    let server = smtp_resolve(stack).await?;
    let mut rx = [0u8; 1024];
    let mut tx = [0u8; 1024];
    let mut socket = TcpSocket::new(stack, &mut rx, &mut tx);
    match with_timeout(
        Duration::from_secs(15),
        socket.connect((server, SMTP_PORT)),
    )
    .await
    {
        Ok(Ok(())) => {}
        Ok(Err(error)) => {
            log::warn!("smtp: connect rejected: {:?}", error);
            return Err(SmtpError::Connect);
        }
        Err(_) => {
            log::warn!("smtp: connect timed out");
            return Err(SmtpError::Connect);
        }
    }

    // Server greeting.
    smtp_expect(&mut socket, 2).await?;
    // Identify.
    smtp_send_line(&mut socket, b"EHLO rusty-platform").await?;
    smtp_expect(&mut socket, 2).await?;

    if !SMTP_USERNAME.is_empty() && !SMTP_PASSWORD.is_empty() {
        // AUTH LOGIN: the server challenges (334), we answer with base64(user) then base64(pass).
        smtp_send_line(&mut socket, b"AUTH LOGIN").await?;
        smtp_expect(&mut socket, 3).await?;
        let mut user = [0u8; 128];
        smtp_send_line(&mut socket, base64_encode(SMTP_USERNAME, &mut user).as_bytes()).await?;
        smtp_expect(&mut socket, 3).await?;
        let mut pass = [0u8; 128];
        smtp_send_line(&mut socket, base64_encode(SMTP_PASSWORD, &mut pass).as_bytes()).await?;
        smtp_expect(&mut socket, 2).await?;
    } else {
        log::warn!("smtp: no username/password; sending unauthenticated");
    }

    for recipient in SMTP_SUBSCRIPTIONS {
        smtp_send_line(&mut socket, b"MAIL FROM:<").await?;
        socket.write_all(SMTP_FROM.as_bytes()).await.map_err(|_| SmtpError::Io)?;
        smtp_send_line(&mut socket, b">").await?;
        smtp_expect(&mut socket, 2).await?;

        smtp_send_line(&mut socket, b"RCPT TO:<").await?;
        socket.write_all(recipient.as_bytes()).await.map_err(|_| SmtpError::Io)?;
        smtp_send_line(&mut socket, b">").await?;
        smtp_expect(&mut socket, 2).await?;

        smtp_send_line(&mut socket, b"DATA").await?;
        smtp_expect(&mut socket, 3).await?; // 354

        // Each header is ONE line: "Subject: " written on its own would end the header at the
        // colon and leave the subject text as a malformed header of its own, which a relay is
        // entitled to reject.
        smtp_send_parts(&mut socket, &[b"From: <", SMTP_FROM.as_bytes(), b">"]).await?;
        smtp_send_parts(&mut socket, &[b"To: <", recipient.as_bytes(), b">"]).await?;
        smtp_send_parts(&mut socket, &[b"Subject: ", SMTP_KEEPALIVE_SUBJECT.as_bytes()]).await?;
        smtp_send_line(&mut socket, b"").await?; // blank line ends the headers

        // A body line starting with "." would end the DATA early; SMTP escapes it by doubling.
        if SMTP_KEEPALIVE_BODY.starts_with('.') {
            socket.write_all(b".").await.map_err(|_| SmtpError::Io)?;
        }
        smtp_send_line(&mut socket, SMTP_KEEPALIVE_BODY.as_bytes()).await?;
        smtp_send_line(&mut socket, b".").await?; // a line with only "." ends the data
        smtp_expect(&mut socket, 2).await?; // 250
    }

    // Best-effort sign-off: a refused connection here must not be fatal.
    let _ = smtp_send_line(&mut socket, b"QUIT").await;
    let _ = smtp_expect(&mut socket, 2).await;
    socket.abort();
    Ok(())
}

/// One SNTP request, and the local time of day from its answer. The same query net.rs makes, so a
/// design with the SMTP client and one without get their time from the same server and the same
/// offset.
async fn ntp_time(stack: embassy_net::Stack<'static>) -> Option<(u8, u8, u8)> {
    // The server is a name, so the stack's resolver is used first. A literal address would skip
    // this, but a hard-coded one is a server that can move.
    let addresses = with_timeout(
        Duration::from_secs(10),
        stack.dns_query(NTP_SERVER, DnsQueryType::A),
    )
    .await
    .ok()?
    .ok()?;
    let server = match addresses.first()? {
        embassy_net::IpAddress::Ipv4(address) => *address,
        #[allow(unreachable_patterns)]
        _ => return None,
    };

    let mut rx_meta = [PacketMetadata::EMPTY; 2];
    let mut rx_buffer = [0u8; 64];
    let mut tx_meta = [PacketMetadata::EMPTY; 1];
    let mut tx_buffer = [0u8; 64];
    let mut socket = UdpSocket::new(
        stack,
        &mut rx_meta,
        &mut rx_buffer,
        &mut tx_meta,
        &mut tx_buffer,
    );
    if socket.bind(0).is_err() {
        return None;
    }

    // LI 0, version 4, mode 3 (client); everything else zero is a valid SNTP request.
    let mut request = [0u8; 48];
    request[0] = 0x23;
    socket.send_to(&request, (server, 123)).await.ok()?;

    let mut response = [0u8; 48];
    let (length, _) = with_timeout(
        Duration::from_secs(5),
        socket.recv_from(&mut response),
    )
    .await
    .ok()?
    .ok()?;
    if length < 48 {
        return None;
    }
    // The transmit timestamp is the last eight bytes: seconds since 1900, big endian, then the
    // fraction -- which a clock that shows whole seconds has no use for.
    let seconds =
        u32::from_be_bytes([response[40], response[41], response[42], response[43]]) as i64;
    if seconds == 0 {
        return None;
    }
    let unix = seconds - 2_208_988_800;
    let local = unix + tz_offset_minutes() * 60;
    let day = local.rem_euclid(86_400);
    Some(((day / 3600) as u8, ((day / 60) % 60) as u8, (day % 60) as u8))
}

/// Resolve SMTP_HOST to one address. Mirrors net.rs's DNS + send_to step so the address handling is
/// known-good: only the IPv4 branch is taken, the same one the time task uses.
async fn smtp_resolve(
    stack: embassy_net::Stack<'static>,
) -> Result<core::net::Ipv4Addr, SmtpError> {
    let addresses = with_timeout(
        Duration::from_secs(10),
        stack.dns_query(SMTP_HOST, DnsQueryType::A),
    )
    .await
    .ok()
    .and_then(|result| result.ok())
    .ok_or(SmtpError::Resolve)?;
    match addresses.first() {
        Some(embassy_net::IpAddress::Ipv4(address)) => Ok(*address),
        #[allow(unreachable_patterns)]
        _ => {
            log::warn!("smtp: {} did not resolve", SMTP_HOST);
            Err(SmtpError::Resolve)
        }
    }
}

/// Write one line of the dialogue (the payload, then CRLF).
async fn smtp_send_line(socket: &mut TcpSocket<'_>, line: &[u8]) -> Result<(), SmtpError> {
    smtp_send_parts(socket, &[line]).await
}

/// Write one line assembled from several slices (then CRLF). Header fields such as
/// "Subject: x" are a keyword and a value, so they must not go out as two lines.
async fn smtp_send_parts(socket: &mut TcpSocket<'_>, parts: &[&[u8]]) -> Result<(), SmtpError> {
    for part in parts {
        socket.write_all(part).await.map_err(|_| SmtpError::Io)?;
    }
    socket.write_all(CRLF).await.map_err(|_| SmtpError::Io)?;
    Ok(())
}

/// Read server replies until a final one and check its class.
///
/// A reply may span several lines: every line but the last begins with the code and a '-' instead of
/// a space (RFC 5321). The separator of the *current* line is what says whether the reply has ended,
/// which is why the first four bytes of each line are tracked separately -- testing the buffer's own
/// fourth byte would keep finding the first line's '-' and read forever on an EHLO reply, which is
/// nearly always multiline (250-PIPELINING, 250-AUTH, ...).
async fn smtp_expect(socket: &mut TcpSocket<'_>, want: u8) -> Result<(), SmtpError> {
    let mut buf = [0u8; 512];
    let mut len = 0usize;
    let mut head = [0u8; 4];
    let mut at = 0usize;
    loop {
        let mut byte = [0u8; 1];
        match socket.read(&mut byte).await {
            Ok(0) => return Err(SmtpError::Closed),
            Ok(_) => {
                if len < buf.len() {
                    buf[len] = byte[0];
                    len += 1;
                }
                if at < head.len() {
                    head[at] = byte[0];
                    at += 1;
                }
            }
            Err(error) => {
                log::warn!("smtp: reading a reply failed: {:?}", error);
                return Err(SmtpError::Io);
            }
        }
        if byte[0] == 10 {
            // 10 is LF: one line of the reply is complete. A '-' as its fourth byte means more
            // lines follow; anything else (normally a space) ends the reply.
            let more = at >= 4 && head[3] == b'-';
            if !more {
                if at >= 3 && head[0] == b'0' + want {
                    return Ok(());
                }
                log::warn!(
                    "smtp: server replied {}",
                    core::str::from_utf8(&buf[..len]).unwrap_or("<invalid>")
                );
                return Err(SmtpError::Protocol);
            }
            at = 0;
        }
    }
}

/// Standard base64 (the variant AUTH LOGIN expects), into a caller-owned buffer. No allocation.
const BASE64_ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
fn base64_encode<'a>(input: &'a str, out: &'a mut [u8]) -> &'a str {
    let bytes = input.as_bytes();
    let mut o = 0usize;
    let mut i = 0usize;
    while i + 3 <= bytes.len() {
        let b0 = bytes[i];
        let b1 = bytes[i + 1];
        let b2 = bytes[i + 2];
        out[o] = BASE64_ALPHABET[((b0 >> 2) & 0x3f) as usize];
        out[o + 1] = BASE64_ALPHABET[(((b0 << 4) | (b1 >> 4)) & 0x3f) as usize];
        out[o + 2] = BASE64_ALPHABET[(((b1 << 2) | (b2 >> 6)) & 0x3f) as usize];
        out[o + 3] = BASE64_ALPHABET[(b2 & 0x3f) as usize];
        o += 4;
        i += 3;
    }
    let rem = bytes.len() - i;
    if rem == 1 {
        let b0 = bytes[i];
        out[o] = BASE64_ALPHABET[((b0 >> 2) & 0x3f) as usize];
        out[o + 1] = BASE64_ALPHABET[((b0 << 4) & 0x3f) as usize];
        out[o + 2] = b'=';
        out[o + 3] = b'=';
        o += 4;
    } else if rem == 2 {
        let b0 = bytes[i];
        let b1 = bytes[i + 1];
        out[o] = BASE64_ALPHABET[((b0 >> 2) & 0x3f) as usize];
        out[o + 1] = BASE64_ALPHABET[(((b0 << 4) | (b1 >> 4)) & 0x3f) as usize];
        out[o + 2] = BASE64_ALPHABET[((b1 << 2) & 0x3f) as usize];
        out[o + 3] = b'=';
        o += 4;
    }
    core::str::from_utf8(&out[..o]).unwrap_or("")
}

/// Failures are logged by the caller; the variant is only used for control flow.
#[derive(Debug)]
enum SmtpError {
    Connect,
    Io,
    Closed,
    Resolve,
    Protocol,
}
`;
}

/**
 * Inserts `mod smtp;` into `src/main.rs` and returns the edited text.
 *
 * The anchor is the clock module's declaration -- present in every Designer project -- so the two
 * modules land side by side and the user can see they are peers of `net`. Returns the new text and a
 * note about what happened: 'added' when the declaration was inserted, 'present' when smtp was
 * already declared, or 'manual' when the anchor could not be found and the user must add it by hand.
 */
export function declareSmtpModule(mainRs: string): { text: string; note: 'added' | 'present' | 'manual' } {
    if (/#\[cfg\(feature = "smtp"\)\]\s*\nmod smtp;/.test(mainRs)) {
        return { text: mainRs, note: 'present' };
    }
    // A project set up by 0.13.3 declared the module unconditionally. Gate it in place, or the Designer's
    // switch would have nothing to take out of the build (the file would keep compiling either way).
    if (/^mod smtp;$/m.test(mainRs)) {
        return { text: mainRs.replace(/^mod smtp;$/m, '#[cfg(feature = "smtp")]\nmod smtp;'), note: 'added' };
    }
    const declaration = '// SMTP client written by the Rusty Platform SMTP wizard. The `smtp` cargo feature is what\n'
        + '// compiles it in and spawns its task, so the Designer switch can take it out of the build\n'
        + '// without deleting the file.\n'
        + '#[cfg(feature = "smtp")]\nmod smtp;\n';
    // The clock module is declared in every Designer project; its comment is a stable anchor.
    const anchor = /(\/\/ Where the time comes from when no PC is listening on the cable.\nmod net;\n)/;
    if (anchor.test(mainRs)) {
        return { text: mainRs.replace(anchor, `$1\n${declaration}`), note: 'added' };
    }
    // Fall back to the design's own modules, where every Designer project also has them.
    const fallback = /(\/\/ The design's own module, and the code-behind it calls.\nmod ui;\nmod ui_handlers;\n)/;
    if (fallback.test(mainRs)) {
        return { text: mainRs.replace(fallback, `$1\n${declaration}`), note: 'added' };
    }
    return { text: `${declaration}\n${mainRs}`, note: 'manual' };
}

/**
 * Spawns the SMTP task from `setup()`, replacing the clock's own spawn.
 *
 * This is the merge that makes the radio shared: `peripherals.WIFI` can be moved once per boot, so with the
 * SMTP client compiled in its task also does the clock's network time query, and net.rs's `time_task` is
 * only compiled/spawned when the feature is off. Both statements are `#[cfg]`-gated statements, so exactly
 * one of them exists in any build and the peripheral is moved once.
 *
 * Returns the edited text; 'present' when the merged shape is already there, 'manual' when the clock's
 * spawn could not be found.
 */
export function wireSmtpSpawn(mainRs: string): { text: string; note: 'added' | 'present' | 'manual' } {
    // The merged shape this function writes (and the generator emits): the SMTP task is given the clock's
    // answer as its second argument.
    if (/smtp_task\(peripherals\.WIFI,/.test(mainRs)) {
        return { text: mainRs, note: 'present' };
    }
    const merged = `    // One task owns the radio: peripherals.WIFI can be moved once per boot, so with the SMTP
    // client compiled in its task also does the clock's network time query.
    #[cfg(feature = "smtp")]
    spawner.spawn(
        crate::smtp::smtp_task(peripherals.WIFI, ui::HAS_CLOCK && needs_time)
            .expect("the SMTP task is spawned exactly once"),
    );
    #[cfg(not(feature = "smtp"))]
    if ui::HAS_CLOCK && needs_time {
        spawner.spawn(
            crate::net::time_task(peripherals.WIFI).expect("the network time task is spawned exactly once"),
        );
    }`;
    // 0.13.3 put SMTP in the `else` of that block, so the two tasks took turns owning the radio. That shape
    // is lifted into the merged one: the clock's query now happens inside the SMTP task instead.
    const legacyPair = /(    if ui::HAS_CLOCK && needs_time \{\n        spawner\.spawn\(\n            crate::net::time_task\(peripherals\.WIFI\)\.expect\("the network time task is spawned exactly once"\),\n        \);\n    \} else \{[\s\S]*?\n    \})/;
    if (legacyPair.test(mainRs)) {
        return { text: mainRs.replace(legacyPair, merged), note: 'added' };
    }
    const clockOnly = /(    if ui::HAS_CLOCK && needs_time \{\n        spawner\.spawn\(\n            crate::net::time_task\(peripherals\.WIFI\)\.expect\("the network time task is spawned exactly once"\),\n        \);\n    \})/;
    if (clockOnly.test(mainRs)) {
        return { text: mainRs.replace(clockOnly, merged), note: 'added' };
    }
    return { text: mainRs, note: 'manual' };
}

/**
 * Makes the manifest able to carry the SMTP switch: a `smtp = []` definition, enabled in `default`.
 *
 * A project generated before the feature existed has no table to move, so the definition is written first
 * (`default = ["smtp"]` naming an undefined feature is a cargo error). The wizard calls this on every run,
 * which also means re-running it turns the switch back on.
 */
export function ensureSmtpFeature(cargoToml: string): { text: string; note: 'added' | 'present' } {
    const defined = ensureFeatureDefinition(cargoToml, 'smtp');
    const enabled = setFeatureInDefault(defined.text, 'smtp', true);
    const changed = defined.note === 'added' || enabled.note !== 'none';
    return { text: enabled.text, note: changed ? 'added' : 'present' };
}

/**
 * Makes net.rs accept that its clock task is compiled-but-unspawned when the SMTP client owns the radio.
 *
 * `peripherals.WIFI` can be moved once, so the SMTP task does the time query itself in that build and
 * net.rs's `time_task` is never spawned -- which rustc reports as six dead items. They are the other half
 * of the Designer's switch: turning SMTP off brings the clock back without regenerating a project file, so
 * the module says so with `#![allow(dead_code)]` rather than deleting code that is still needed.
 *
 * Generated projects carry the line already; this is what an older project gets when the wizard runs.
 */
export function ensureNetAllowDeadCode(netRs: string): { text: string; note: 'added' | 'present' } {
    if (/#!\[allow\(dead_code\)\]/.test(netRs)) {
        return { text: netRs, note: 'present' };
    }
    const anchor = /^use\s/m;
    if (!anchor.test(netRs)) {
        return { text: netRs, note: 'present' };
    }
    const note = '// The SMTP task owns the radio when the `smtp` feature is on, so this module\'s task is\n'
        + '// compiled but not spawned in that build; its items are the other half of the Designer switch.\n'
        + '#![allow(dead_code)]\n\n';
    return { text: netRs.replace(anchor, `${note}$&`), note: 'added' };
}

/**
 * Ensures the `embassy-net` dependency carries the `tcp` feature the SMTP client needs.
 *
 * Returns the (possibly unchanged) Cargo.toml text and a note: 'added', 'present', or 'opaque' when
 * the entry is written in a form this editor will not rewrite.
 */
export function enableEmbassyTcp(cargoToml: string): { text: string; note: 'added' | 'present' | 'opaque' } {
    const model = parseCargoToml(cargoToml);
    const existing = findDependency(model, 'embassy-net');
    if (existing === undefined) {
        return { text: cargoToml, note: 'opaque' };
    }
    if (existing.form === 'opaque' || (existing.features ?? []).includes('tcp')) {
        return { text: cargoToml, note: existing.form === 'opaque' ? 'opaque' : 'present' };
    }
    const outcome = applyDependency(cargoToml, {
        name: 'embassy-net',
        version: existing.version,
        features: [...(existing.features ?? []), 'tcp'],
    });
    if (!outcome.ok) {
        return { text: cargoToml, note: 'opaque' };
    }
    return { text: outcome.text, note: 'added' };
}

/**
 * Adds `embedded-io-async` as a direct dependency so `smtp.rs` can name the `Read`/`Write` traits
 * `embassy-net` 0.9 already implements for `TcpSocket`. It is already a transitive dependency
 * (through `embassy-net`), so this just makes the version nameable.
 */
export function addEmbeddedIoAsyncDep(cargoToml: string): { text: string; note: 'added' | 'present' | 'opaque' } {
    const model = parseCargoToml(cargoToml);
    const existing = findDependency(model, 'embedded-io-async');
    if (existing !== undefined) {
        return { text: cargoToml, note: 'present' };
    }
    const outcome = applyDependency(cargoToml, {
        name: 'embedded-io-async',
        version: '0.7',
        features: [],
    });
    if (!outcome.ok) {
        return { text: cargoToml, note: 'opaque' };
    }
    return { text: outcome.text, note: 'added' };
}
