// ------------------------------------------------------------- the time over Wi-Fi

/**
 * `src/net.rs` for a W board: join the network the build was given and ask an NTP server for the time.
 *
 * The ESP side has the same module for the same reason. On a Pico the radio's pins arrive in
 * `panel::Rest`, because `panel::init` took the peripheral set by value -- so this module builds the
 * CYW43's PIO SPI itself rather than being handed one, and reads nothing from `main.rs` but that value.
 */
export function emitRpNetRs(board: RpBoardProfile): string {
    const cyw = board.cyw43;
    if (cyw === undefined) {
        throw new Error(`emitRpNetRs: ${board.id} has no CYW43 wiring`);
    }
    const field = (pinName: string): string => `pin${pinName.slice(4)}`;
    return `// Generated by Grumpy's Rusty Platform for VS Code.
//
// The time without a host: Wi-Fi and SNTP.
//
// A Pico has no RTC on the chip, so a clock design needs a starting point. \`main.rs\` seeds it from the
// build's own time; this module corrects that from the network when the board is on one, and publishes
// the local time of day for the loop to put on the glass.
//
// Compiled only with the \`time-wifi\` feature, which the Designer's Time source switch moves -- so a
// project that takes its time from a battery-backed module later pays for none of this.
#![allow(dead_code)]

use cyw43::aligned_bytes;
use cyw43_pio::{${cyw.clockDivider}, PioSpi};
use defmt::{info, warn};
use embassy_net::dns::DnsQueryType;
use embassy_net::udp::{PacketMetadata, UdpSocket};
use embassy_net::{Config as NetConfig, Stack, StackResources};
use embassy_rp::clocks::RoscRng;
use embassy_rp::gpio::{Level, Output};
use embassy_rp::peripherals::{${cyw.dmaCh0}, ${cyw.pio}};
use embassy_rp::pio::{InterruptHandler, Pio};
use embassy_rp::{bind_interrupts, dma};
use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
use embassy_sync::signal::Signal;
use embassy_time::{with_timeout, Duration, Timer};
use static_cell::StaticCell;

use crate::panel::Rest;

bind_interrupts!(struct Irqs {
    ${cyw.pio}_IRQ_0 => InterruptHandler<${cyw.pio}>;
    DMA_IRQ_0 => dma::InterruptHandler<${cyw.dmaCh0}>;
});

/// The local time of day an NTP server gave, waiting for the main loop to put it on the design.
///
/// Seconds only, because that is what a Clock widget draws: the date would be a second fact with its own
/// leap-second questions, and a Pico design that needs one can read \`BUILD_EPOCH\` in the header.
pub static SYNCED_TIME: Signal<CriticalSectionRawMutex, (u8, u8, u8)> = Signal::new();

/// The network the build was given. The same contract as the Wi-Fi template: read at compile time, never
/// in the source tree, and filled in by the credential prompt before a build.
const WIFI_SSID: &str = match option_env!("WIFI_SSID") {
    Some(value) => value,
    None => "YOUR_WIFI_SSID",
};
const WIFI_PASSWORD: &str = match option_env!("WIFI_PASSWORD") {
    Some(value) => value,
    None => "YOUR_WIFI_PASSWORD",
};

/// The time server: \`pool.ntp.org\` resolves to a nearby one and is the usual choice.
const NTP_SERVER: &str = "pool.ntp.org";

/// The stack's buffer pool has to outlive the task, so it is a static. Written once: the task is spawned
/// at most once per boot.
static STACK_RESOURCES: StaticCell<StackResources<3>> = StaticCell::new();

/// Runs the firmware half of the CYW43 driver. Spawned by the task below, and it owns the runner for good.
#[embassy_executor::task]
async fn cyw43_task(
    runner: cyw43::Runner<'static, cyw43::SpiBus<Output<'static>, PioSpi<'static, ${cyw.pio}, 0>>>,
) -> ! {
    runner.run().await
}

/// Drives the network stack: no packet moves while it is not being polled.
#[embassy_executor::task]
async fn net_task(mut runner: embassy_net::Runner<'static, cyw43::NetDriver<'static>>) -> ! {
    runner.run().await
}

/// Joins the network, asks the time server, and publishes the answer.
///
/// A board with no network keeps the design's own time (the build time), which is why every failure here is
/// a log line and a return rather than a panic: a clock that is a little behind is a working clock.
#[embassy_executor::task]
pub async fn time_task(rest: Rest) {
    let fw = aligned_bytes!("../firmware/43439A0.bin");
    let clm = aligned_bytes!("../firmware/43439A0_clm.bin");
    let nvram = aligned_bytes!("../firmware/nvram_rp2040.bin");

    // The chip's four pins came back from panel::init for exactly this. Its power switch starts low (the
    // chip is held off until the driver is ready) and the chip select high, as the vendor examples do.
    let pwr = Output::new(rest.${field(cyw.pwrPin)}, Level::Low);
    let cs = Output::new(rest.${field(cyw.csPin)}, Level::High);
    let mut pio = Pio::new(rest.pio0, Irqs);
    let spi = PioSpi::new(
        &mut pio.common,
        pio.sm0,
        ${cyw.clockDivider},
        pio.irq0,
        cs,
        rest.${field(cyw.dioPin)},
        rest.${field(cyw.clkPin)},
        dma::Channel::new(rest.dma_ch0, Irqs),
    );

    static STATE: StaticCell<cyw43::State> = StaticCell::new();
    let state = STATE.init(cyw43::State::new());
    let (net_device, mut control, runner) = cyw43::new(state, pwr, spi, fw, nvram).await;
    // Both tasks are spawned from inside a task: for_current_executor is unsafe because it reads the
    // executor out of the current waker, and being inside a task is the condition it asks for.
    let spawner = unsafe { embassy_executor::Spawner::for_current_executor().await };
    spawner.spawn(cyw43_task(runner).expect("the CYW43 task is spawned exactly once"));

    control.init(clm).await;
    control
        .set_power_management(cyw43::PowerManagementMode::PowerSave)
        .await;

    let mut rng = RoscRng;
    let seed = rng.next_u64();
    let (stack, net_runner) = embassy_net::new(
        net_device,
        NetConfig::dhcpv4(Default::default()),
        STACK_RESOURCES.init(StackResources::new()),
        seed,
    );
    spawner.spawn(net_task(net_runner).expect("the network task is spawned exactly once"));

    let mut joined = false;
    for attempt in 1..=5u32 {
        info!("clock: joining {} (attempt {})", WIFI_SSID, attempt);
        match control
            .join(WIFI_SSID, cyw43::JoinOptions::new(WIFI_PASSWORD.as_bytes()))
            .await
        {
            Ok(()) => {
                joined = true;
                break;
            }
            Err(error) => {
                warn!("clock: association failed ({:?})", error);
                Timer::after(Duration::from_secs(5)).await;
            }
        }
    }
    if !joined {
        warn!("clock: no network; the design keeps the build time");
        return;
    }

    // A router that has the lease ready is quick; one that does not is a board with no network, and a
    // clock should not wait on it for ever.
    if with_timeout(Duration::from_secs(30), stack.wait_config_up())
        .await
        .is_err()
    {
        warn!("clock: no address from DHCP; the design keeps the build time");
        return;
    }

    for attempt in 1..=3u32 {
        if let Some((hour, minute, second)) = sntp_time(stack).await {
            info!(
                "clock: the network says {:02}:{:02}:{:02} (attempt {})",
                hour, minute, second, attempt
            );
            SYNCED_TIME.signal((hour, minute, second));
            return;
        }
        Timer::after(Duration::from_secs(2)).await;
    }
    warn!("clock: the time server did not answer; the design keeps the build time");
}

/// Asks the time server for the time of day, in local time.
///
/// A 48-byte SNTP request: version 3, mode 3 (client) in the first byte, everything else zero. The server
/// answers with the transmit timestamp at bytes 40..44, in seconds since 1900, which is 2,208,988,800
/// before the Unix epoch.
async fn sntp_time(stack: Stack<'static>) -> Option<(u8, u8, u8)> {
    let addresses = stack.dns_query(NTP_SERVER, DnsQueryType::A).await.ok()?;
    let address = *addresses.first()?;

    let mut rx_meta = [PacketMetadata::EMPTY; 1];
    let mut tx_meta = [PacketMetadata::EMPTY; 1];
    let mut rx_buffer = [0u8; 128];
    let mut tx_buffer = [0u8; 128];
    let mut socket = UdpSocket::new(
        stack,
        &mut rx_meta,
        &mut rx_buffer,
        &mut tx_meta,
        &mut tx_buffer,
    );
    socket.bind(0).ok()?;

    let request = [0x1bu8; 1];
    let mut packet = [0u8; 48];
    packet[0] = request[0];
    socket.send_to(&packet, (address, 123)).await.ok()?;

    let mut response = [0u8; 48];
    let (length, _) = with_timeout(Duration::from_secs(5), socket.recv_from(&mut response))
        .await
        .ok()?
        .ok()?;
    if length < 48 {
        return None;
    }
    let seconds = u32::from_be_bytes([response[40], response[41], response[42], response[43]]);
    let unix = i64::from(seconds) - 2_208_988_800;
    let local = unix + crate::main_header::UTC_OFFSET_MINUTES * 60;
    let of_day = local.rem_euclid(86_400);
    Some(((of_day / 3_600) as u8, ((of_day % 3_600) / 60) as u8, (of_day % 60) as u8))
}
`;
}
