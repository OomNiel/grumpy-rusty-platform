/**
 * The `src/sd.rs` a Designer project gets on a board whose catalog entry declares a card.
 *
 * Kept apart from `esp.ts` for the same reason the ESP generator itself is apart from the RP one: this is a
 * whole Rust module, and the generator around it is already the longest file in `src/generate/`.
 *
 * The widget that reads from it (`rusty-gui-widgets::BmpImage`) is already written and lives in the vendored
 * `codegen/` tree of every Designer project. What it asks for is one function, `with_file`, which it holds as
 * a plain `fn` pointer; everything else here exists to make that function possible: the SPI bus, the FAT
 * mount, and a static to keep the mount alive between calls.
 *
 * The module is generated only for a Designer project on a board with an SD card, so the card's pins are the
 * catalog's, not a guess.
 */

import type { EspBoardProfile } from '../boards/types';

/**
 * The SPI peripheral the card is wired to.
 *
 * Not the panel's. The panel takes SPI2 on every board with a card, and esp-hal's `Spi` owns its peripheral
 * for good once a driver has been handed one, so the socket goes on the chip's second bus (SPI3 on the
 * classic ESP32). The socket's pins (18/23/19 on the CYD) are chosen to be reachable through the GPIO matrix
 * from that second bus, which is why this is possible at all.
 */
export const DESIGNER_SD_PERIPHERAL = 'SPI3';

/**
 * The Rust source of `src/sd.rs`.
 *
 * Throws when the board has no card rather than emitting a module that cannot compile: the caller decides
 * whether a card is present (`board.sd !== undefined`), and a silent `false`/empty module here would hide a
 * mistake one layer up.
 */
export function emitSdRs(board: EspBoardProfile): string {
    const sd = board.sd;
    if (sd === undefined) {
        throw new Error(`emitSdRs called for ${board.id}, which declares no SD card`);
    }
    return `// Generated by Grumpy's Rusty Platform for VS Code.
// Board: ${board.name} (${board.family})
//
// The microSD card, and the reader a design's image widgets call through.
//
// A Designer project's image controls can name a file on the card instead of embedding its pixels: the
// design writes the path as "sd:/PIC1.BMP", and the widget calls \`with_file\` on every draw. This module
// owns the card's SPI bus and its FAT filesystem, and keeps them mounted between calls.

use core::cell::RefCell;

use critical_section::Mutex;
use embedded_hal_bus::spi::ExclusiveDevice;
use embedded_sdmmc::{
    Mode, RawFile, RawVolume, SdCard, TimeSource, Timestamp, VolumeIdx, VolumeManager,
};
use esp_hal::delay::Delay;
use esp_hal::gpio::interconnect::{PeripheralInput, PeripheralOutput};
use esp_hal::gpio::{Level, Output, OutputConfig, OutputPin};
use esp_hal::spi::master::{Config as SpiConfig, Instance, Spi};
use esp_hal::time::Rate;

/// The card's clock, in kHz.
///
/// The SD specification requires a card to initialise at or below 400 kHz, and this stays there for the data
/// phase too: a correct slow read beats a fast one that corrupts a sector. embedded-sdmmc 0.8 has a
/// clock-controller hook (\`new_with_options\`) for raising it after the handshake, but nothing here needs it.
const SD_CLOCK_KHZ: u32 = 400;

/// The clock the filesystem stamps on anything it writes. This module only ever reads, so a fixed timestamp
/// is honest rather than a pretended wall clock; it is also what the crate's own example does.
struct FixedClock;

impl TimeSource for FixedClock {
    fn get_timestamp(&self) -> Timestamp {
        // Years are counted from 1970 and months and days from zero: 56 is 2026.
        Timestamp {
            year_since_1970: 56,
            zero_indexed_month: 0,
            zero_indexed_day: 0,
            hours: 0,
            minutes: 0,
            seconds: 0,
        }
    }
}

/// The concrete card: the SPI bus, its chip select, and the crate's driver on top.
type Card =
    SdCard<ExclusiveDevice<Spi<'static, esp_hal::Blocking>, Output<'static>, Delay>, Delay>;

/// The mounted filesystem, kept together with the volume handle that was opened on it.
///
/// \`RawVolume\` and \`RawFile\` are plain, copyable values, which is exactly what makes it legal to keep
/// them in a \`static\`: the crate's ergonomic \`Volume\`/\`Directory\`/\`File\` wrappers borrow the manager and
/// could not be stored between calls.
type Mounted = (VolumeManager<Card, FixedClock>, RawVolume);

/// The card, mounted once from \`init\` and kept for the life of the program.
static MOUNTED: Mutex<RefCell<Option<Mounted>>> = Mutex::new(RefCell::new(None));

/// Mounts the card and stores the mounted volume for \`with_file\`.
///
/// Called once from \`main\`, before the panel and the design come up, so the first image a design draws
/// already has somewhere to read from. Re-mounting on every draw would read the partition table and the FAT
/// boot sector again each time, which is why the volume is opened here and kept.
///
/// The pins are the TF socket's, not the panel's. A driver owns its bus for good once it has been handed one,
/// so the card gets its own SPI peripheral and the panel keeps the other one.
///
/// The chip select is taken as an \`OutputPin\` rather than a \`PeripheralOutput\`: \`Output::new\` needs the
/// former, and the driver wraps it into the \`SpiDevice\` that holds CS across a transaction. The three bus
/// lines are \`PeripheralOutput\`/\`PeripheralInput\`, which is what \`Spi::with_sck\` and friends ask for. That
/// split is esp-hal's, and it was found by compiling a generated project rather than by reading the docs.
pub fn init(
    spi: impl Instance + 'static,
    cs: impl OutputPin + 'static,
    sck: impl PeripheralOutput<'static> + 'static,
    mosi: impl PeripheralOutput<'static> + 'static,
    miso: impl PeripheralInput<'static> + 'static,
) {
    let spi = Spi::new(
        spi,
        // 400 kHz: the clock a card is specified to initialise at, and what it is read at here.
        SpiConfig::default().with_frequency(Rate::from_khz(SD_CLOCK_KHZ)),
    )
    .expect("SPI configuration")
    .with_sck(sck)
    .with_mosi(mosi)
    .with_miso(miso);

    let cs = Output::new(cs, Level::Low, OutputConfig::default());
    let device = ExclusiveDevice::new(spi, cs, Delay::new()).expect("card chip select");

    log::info!(
        "sd: mounting (cs GPIO${sd.cs}, sclk GPIO${sd.spi.sclk}, mosi GPIO${sd.spi.mosi}, miso GPIO${sd.spi.miso})"
    );

    let card = SdCard::new(device, Delay::new());
    match card.num_bytes() {
        Ok(bytes) => log::info!("sd: card reports {} bytes ({} MiB)", bytes, bytes / (1024 * 1024)),
        Err(error) => log::error!("sd: the card did not answer ({:?})", error),
    }

    let mut volumes = VolumeManager::new(card, FixedClock);
    match volumes.open_raw_volume(VolumeIdx(0)) {
        Ok(volume) => {
            log::info!("sd: volume 0 mounted - sd: images will be read from the card");
            critical_section::with(|token| {
                *MOUNTED.borrow_ref_mut(token) = Some((volumes, volume));
            });
        }
        Err(error) => log::error!(
            "sd: no volume 0 - is the card inserted and FAT formatted? ({:?})",
            error
        ),
    }
}

/// Runs \`use_file\` with \`path\` open for as long as the closure needs it.
///
/// A callback rather than an open/read/close triple because the reader borrows the mounted volume: the borrow
/// ends when the closure returns, so nothing that borrows the static is ever stored, and the one critical
/// section covers the whole read.
///
/// \`path\` is a FAT **short name** (8.3), with or without a leading slash: the design writes "sd:/PIC1.BMP"
/// and this is handed "PIC1.BMP". embedded-sdmmc 0.8 has no long-name support at all -- it is a \`no_std\`
/// crate with no allocator -- so a long name such as "holiday photo.bmp" is a file the driver cannot look
/// up. Keep the names on the card short.
///
/// Any failure at all becomes \`Err(())\`: the widget treats that as "there is nothing to draw".
///
/// Allowed to be unused: the module is generated for the board rather than for one design, and a design
/// that names no \`sd:\` images never calls this.
#[allow(dead_code)]
pub fn with_file(
    path: &str,
    use_file: &mut dyn FnMut(&mut dyn rusty_gui_widgets::ByteSource) -> Result<(), ()>,
) -> Result<(), ()> {
    let name = path.trim_start_matches('/');
    // A path that still has a separator asks for a subdirectory, and this reader only opens the root.
    if name.is_empty() || name.contains('/') {
        return Err(());
    }

    critical_section::with(|token| {
        let mut mounted = MOUNTED.borrow_ref_mut(token);
        let Some((volumes, volume)) = mounted.as_mut() else {
            // No card was mounted at boot, so every image is simply nothing to draw.
            return Err(());
        };

        let directory = volumes.open_root_dir(*volume).map_err(|_| ())?;
        let file = match volumes.open_file_in_dir(directory, name, Mode::ReadOnly) {
            Ok(file) => file,
            Err(_) => {
                // Leave the directory closed: a handle left open would make the next call fail.
                let _ = volumes.close_dir(directory);
                return Err(());
            }
        };

        let result = {
            let mut reader = CardFile {
                volumes: &mut *volumes,
                file,
            };
            use_file(&mut reader)
        };

        // Closed whatever the read did, in the reverse order they were opened.
        let _ = volumes.close_file(file);
        let _ = volumes.close_dir(directory);
        result
    })
}

/// Reads from one open file on the card, as the image widget's \`ByteSource\`.
///
/// Constructed only by \`with_file\`, which is why it is allowed to be unused for the same reason.
#[allow(dead_code)]
struct CardFile<'a> {
    volumes: &'a mut VolumeManager<Card, FixedClock>,
    file: RawFile,
}

impl rusty_gui_widgets::ByteSource for CardFile<'_> {
    fn read(&mut self, buf: &mut [u8]) -> Result<usize, ()> {
        self.volumes.read(self.file, buf).map_err(|_| ())
    }
}
`;
}
