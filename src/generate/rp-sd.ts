/**
 * The `src/sd.rs` a Pico Designer project gets when its card socket is wired.
 *
 * The twin of `esp-sd.ts`, and deliberately the same module in every way that matters: the widget that
 * reads from it (`rusty-gui-widgets::BmpImage`) holds a plain function pointer and calls
 * `with_file(path, sink)`, so this file's job is fixed by that contract. What changes is only the family's
 * bus type and the way its clock is changed.
 *
 * On a Pico the socket usually has its own four pins (`panel::CardSpi`), which is why the mount receives a
 * complete device rather than building one: `panel.rs` owns every pin of the assembly and this file only
 * owns the filesystem.
 */

/**
 * The Rust source of `src/sd.rs`.
 *
 * `sharedBus` says which device type `panel::CardDevice` is -- a `CriticalSectionDevice` over the panel's
 * bus, or an `ExclusiveDevice` over the socket's own SPI.
 *
 * `imageReader` says whether the module carries the reader a design's image widgets call through. A
 * Designer project does; the SD card *test* does not -- it only mounts the card and reports what it found,
 * and pulling the widget crate into it would drag the whole vendored runtime along for one function.
 */
export function emitRpSdRs(options: { sharedBus: boolean; imageReader: boolean }): string {
    const busNote = options.sharedBus
        ? `/// The card sits on the panel's own bus, so its chip select is the only pin of its own.
pub type Card = SdCard<panel::CardDevice, panel::Delay>;`
        : `/// The card has the socket's own SPI peripheral, so this device owns its bus outright -- which is what
/// lets the mount re-clock it after the handshake without disturbing the panel.
pub type Card = SdCard<panel::CardDevice, panel::Delay>;`;

    // The handshake is over; the question is who may change the clock now.
    //
    // With its own bus, the device owns it and `SdCard::spi` hands it back for exactly this. On a shared
    // bus the device is a `CriticalSectionDevice`, which deliberately exposes no way to reach the bus -- so
    // the bus `panel::init` created is used instead, and the change applies to the panel too. That is the
    // honest trade: a panel drawing at 10 MHz is slow, a card read at the panel's 24-40 MHz corrupts.
    const clockSwitch = options.sharedBus
        ? `
    // The socket shares the panel's bus, so one clock serves both. Set it once, here: the panel keeps
    // drawing at this rate from now on.
    let _ = &device;
    critical_section::with(|token| bus.borrow_ref_mut(token).set_frequency(CARD_DATA_CLOCK_HZ));
    info!("sd: reading at {} Hz (the panel shares this bus, so it re-clocks too)", CARD_DATA_CLOCK_HZ);
`
        : `
    // The handshake is over, so the card's own bus is re-clocked for the reads that follow. \`spi\` is the
    // crate's own hook for exactly this: it hands the closure the device the driver holds, and the HAL's
    // \`set_frequency\` recalibrates the peripheral.
    let _ = bus;
    card.spi(|device| device.bus_mut().set_frequency(CARD_DATA_CLOCK_HZ));
    info!("sd: reading at {} Hz", CARD_DATA_CLOCK_HZ);
`;

    // The reader half, only for a project that draws images from the card.
    const imageSupport = options.imageReader
        ? IMAGE_READER
        : `
/// Opens the root directory and counts what is in it.
///
/// This is the card test's answer: a mount that succeeds and a directory that lists nothing is a card with
/// an unreadable filesystem, which the log would otherwise report as a success.
#[allow(dead_code)]
pub fn list_root() -> Option<usize> {
    critical_section::with(|token| {
        let mut mounted = MOUNTED.borrow_ref_mut(token);
        let Some((volumes, volume)) = mounted.as_mut() else {
            return None;
        };
        let directory = volumes.open_root_dir(*volume).ok()?;
        let mut count = 0usize;
        let result = volumes.iterate_dir(directory, |_entry| count += 1);
        let _ = volumes.close_dir(directory);
        result.ok().map(|()| count)
    })
}
`;

    return `// Generated by Grumpy's Rusty Platform for VS Code.
//
// The microSD card, and the reader a design's image widgets call through.
//
// A design can name a file on the card instead of embedding its pixels: the markup writes "sd:/PIC1.BMP"
// and the widget calls \`with_file\` on every draw. This module owns the FAT filesystem and the mounted
// volume; the pins belong to src/panel.rs, so the whole assembly is described in one place.

use core::cell::RefCell;
use core::sync::atomic::{AtomicU32, Ordering};

use critical_section::Mutex;
use defmt::{error, info};
use embedded_sdmmc::{${options.imageReader
            ? 'Mode, RawFile, RawVolume, SdCard, TimeSource, Timestamp, VolumeIdx, VolumeManager'
            : 'RawVolume, SdCard, TimeSource, Timestamp, VolumeIdx, VolumeManager'
        }};

use crate::panel::{self, CARD_DATA_CLOCK_HZ};

${busNote}

/// The card's capacity in MiB, recorded for the diagnostics template.
///
/// MiB rather than bytes because this runs on a Cortex-M0+ as often as not, and that core has no 64-bit
/// atomics: a 64-bit atomic would not compile there. A card that answered with 0 MiB does not exist.
static CARD_MIB: AtomicU32 = AtomicU32::new(0);

/// What the card reported, when it answered at all.
///
/// Read by the sdcard template's screen; a Designer project has no use for the number and must not warn
/// about it.
#[allow(dead_code)]
pub fn card_bytes() -> Option<u64> {
    let mib = CARD_MIB.load(Ordering::Relaxed);
    if mib == 0 {
        None
    } else {
        Some(u64::from(mib) * 1024 * 1024)
    }
}

/// The clock the filesystem stamps on anything it writes. This module only ever reads, so a fixed
/// timestamp is honest rather than a pretended wall clock.
struct FixedClock;

impl TimeSource for FixedClock {
    fn get_timestamp(&self) -> Timestamp {
        // Years count from 1970 and months and days from zero: 56 is 2026.
        Timestamp {
            year_since_1970: 56,
            zero_indexed_month: 0,
            zero_indexed_day: 0,
            hours: 0,
            minutes: 0,
            seconds: 0,
        }
    }
}

/// The mounted filesystem, kept together with the volume handle that was opened on it.
///
/// \`RawVolume\` and \`RawFile\` are plain copyable values, which is what makes them legal in a static: the
/// crate's ergonomic \`Volume\`/\`File\` wrappers borrow the manager and could not be stored between calls.
type Mounted = (VolumeManager<Card, FixedClock>, RawVolume);

/// The card, mounted once from \`init\` and kept for the life of the program.
static MOUNTED: Mutex<RefCell<Option<Mounted>>> = Mutex::new(RefCell::new(None));

/// Mounts the card and stores the mounted volume for \`with_file\`.
///
/// Called once from \`panel::init\`, before the first frame, so the first image a design draws already has
/// somewhere to read from. A card that does not answer is a log line and nothing more: every image is then
/// "nothing to draw", which is exactly what a missing card means.
pub fn init(device: panel::CardDevice, bus: &'static panel::PanelBus) {
    let card = SdCard::new(device, panel::Delay);
    match card.num_bytes() {
        Ok(bytes) => {
            CARD_MIB.store((bytes / (1024 * 1024)) as u32, Ordering::Relaxed);
            info!("sd: card reports {} bytes ({} MiB)", bytes, bytes / (1024 * 1024));
        }
        Err(_) => error!("sd: the card did not answer"),
    }
${clockSwitch}
    let mut volumes = VolumeManager::new(card, FixedClock);
    match volumes.open_raw_volume(VolumeIdx(0)) {
        Ok(volume) => {
            info!("sd: volume 0 mounted - sd: images will be read from the card");
            critical_section::with(|token| {
                *MOUNTED.borrow_ref_mut(token) = Some((volumes, volume));
            });
        }
        Err(_) => error!("sd: no volume 0 - is the card inserted and FAT formatted?"),
    }
}

${imageSupport}`;
}

/**
 * The reader half of the module: the one function a design's image widgets call.
 *
 * A separate constant because two projects want different amounts of this file: a Designer project reads
 * images from the card and needs it, the card test needs the mount and nothing else. Keeping it here rather
 * than in a second module means the mount and the reader can never disagree about the mounted static.
 */
const IMAGE_READER = `
/// Runs use_file with path open for as long as the closure needs it.
///
/// A callback rather than an open/read/close triple because the reader borrows the mounted volume: the
/// borrow ends when the closure returns, so nothing that borrows the static is ever stored, and the one
/// critical section covers the whole read.
///
/// path is a FAT **short name** (8.3), with or without a leading slash: the design writes
/// "sd:/PIC1.BMP" and this is handed "PIC1.BMP". embedded-sdmmc 0.8 has no long-name support at all -- it
/// is a no_std crate with no allocator -- so a name such as "holiday photo.bmp" cannot be looked up.
///
/// Any failure at all becomes Err(()): the widget treats that as "there is nothing to draw".
#[allow(dead_code)]
pub fn with_file(
    path: &str,
    use_file: &mut dyn FnMut(&mut dyn rusty_gui_widgets::ByteSource) -> Result<(), ()>,
) -> Result<(), ()> {
    let name = path.trim_start_matches('/');
    // A path that still has a separator asks for a subdirectory, and this reader only opens the root.
    if name.is_empty() || name.contains('/') {
        return Err(());
    }

    critical_section::with(|token| {
        let mut mounted = MOUNTED.borrow_ref_mut(token);
        let Some((volumes, volume)) = mounted.as_mut() else {
            // No card was mounted at boot, so every image is simply nothing to draw.
            return Err(());
        };

        let directory = volumes.open_root_dir(*volume).map_err(|_| ())?;
        let file = match volumes.open_file_in_dir(directory, name, Mode::ReadOnly) {
            Ok(file) => file,
            Err(_) => {
                // Leave the directory closed: a handle left open would make the next call fail.
                let _ = volumes.close_dir(directory);
                return Err(());
            }
        };

        let result = {
            let mut reader = CardFile {
                volumes: &mut *volumes,
                file,
            };
            use_file(&mut reader)
        };

        // Closed whatever the read did, in the reverse order they were opened.
        let _ = volumes.close_file(file);
        let _ = volumes.close_dir(directory);
        result
    })
}

/// Reads from one open file on the card, as the image widget's ByteSource.
#[allow(dead_code)]
struct CardFile<'a> {
    volumes: &'a mut VolumeManager<Card, FixedClock>,
    file: RawFile,
}

impl rusty_gui_widgets::ByteSource for CardFile<'_> {
    fn read(&mut self, buf: &mut [u8]) -> Result<usize, ()> {
        self.volumes.read(self.file, buf).map_err(|_| ())
    }

    /// Moves the read position forward without transferring the bytes.
    ///
    /// This is what makes a photograph larger than its cell cheap: the widget asks for the source rows it
    /// will actually show and jumps over the rest, and a jump costs a walk along the FAT -- a handful of
    /// sectors -- where reading those rows would cost every one of them.
    fn skip(&mut self, count: u32) -> Result<(), ()> {
        if count > i32::MAX as u32 {
            return Err(());
        }
        self.volumes
            .file_seek_from_current(self.file, count as i32)
            .map_err(|_| ())
    }
}
`;
