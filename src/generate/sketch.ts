/**
 * The Arduino-style sketch layout every generated project is written in.
 *
 * A generated project used to be one `src/main.rs`: every `use` at the top, then a single
 * `#[esp_rtos::main]` (or `#[embassy_executor::main]`) whose body was the whole program — the peripheral
 * bring-up, the state, and the loop, all in one function. That is the shape a Rust example has, and it is not
 * the shape the people this is written for grew up with.
 *
 * It is now the shape of an Arduino sketch, which is what was asked for (2026-10-16, with the user's own
 * reformatted project as the model — `InspectAllTemplate`):
 *
 * - **`src/main.rs`** holds `setup()` and `main()`, and nothing else but what those two need to exist: the
 *   crate attributes, the side-effect imports, the statics, and the `State` struct `setup()` hands back.
 *   `setup()` initiates every peripheral and instantiates every class once; `main()` calls it and runs the
 *   implementation in a loop of its own.
 * - **`src/MainHeader.rs`** is the sketch's header: the `use` list (re-exported, so one `use main_header::*;`
 *   brings the lot into `main.rs`), the type aliases for the nested driver types, the constants, and the helper
 *   types, functions and macros.
 *
 * Two things about the spelling are deliberate:
 *
 * 1. The file is `MainHeader.rs`, capitalised, because that is the name that was asked for — it reads like the
 *    C++ header it stands in for. Rust would lint a module of that name, so the module is declared with an
 *    explicit `#[path]` and a snake-case name: no warning, no `#[allow]`, and the file keeps its name.
 * 2. `use … as _;` imports stay in `main.rs`. They name nothing; they install something (esp-println's logger,
 *    esp-backtrace's panic handler) and only do so where they are compiled, so a re-export is not the same
 *    thing and the crate root is where they belong.
 */

/** Where the header lives inside a generated project. */
export const SKETCH_HEADER_PATH = 'src/MainHeader.rs';

/** The file's own name, for the banner and the errors of anything that writes it. */
export const SKETCH_HEADER_NAME = 'MainHeader.rs';

/**
 * How `main.rs` declares the header.
 *
 * `#[path]` is what keeps the capitalised file name and a warning-free build: the module is `main_header` and
 * the file is `MainHeader.rs`, which is the one combination Rust accepts without complaint.
 */
export const SKETCH_HEADER_MODULE = `// The sketch's header: every import, the type aliases, the constants and the helpers.
// The path is spelled out because the file is named the way the sketch reads it, not the way Rust
// spells a module name.
#[path = "MainHeader.rs"]
mod main_header;
use main_header::*;`;

/** The imports that belong in the crate root, and the ones the header re-exports. */
export interface SplitImports {
    /** `use x as _;` — side effects, which only happen where they are compiled. */
    sideEffects: string[];
    /** Everything else, to be re-exported from the header. */
    header: string[];
}

/** Splits a generated import list the way `main.rs` and `MainHeader.rs` need it split. */
export function splitImports(imports: readonly string[]): SplitImports {
    const sideEffects: string[] = [];
    const header: string[] = [];
    for (const line of imports) {
        if (/^use\s+\S+\s+as\s+_;$/.test(line.trim())) {
            sideEffects.push(line);
        } else {
            header.push(line);
        }
    }
    return { sideEffects, header };
}

/** The same imports, re-exported so `use main_header::*;` brings them into `main.rs`. */
export function reExported(imports: readonly string[]): string[] {
    return imports.map((line) => `pub ${line}`);
}

/** The parts a generated file pair is assembled from. */
export interface SketchParts {
    /** The `// Generated by …` banner, one comment per line, without a trailing newline. */
    banner: string;
    /** The sketch's own imports — the ones that name something. They are re-exported by the header. */
    imports: readonly string[];
    /** Side-effect imports (`use esp_println as _;`), repeated in the crate root. */
    sideEffects: readonly string[];
    /** `mod ui;` declarations, when the sketch is made of more than one module. */
    modules?: string;
    /** Crate attributes and file-scope items that come before `State`: `#![no_std]`, the app descriptor. */
    prologue: string;
    /** Statics the sketch needs at file scope (`StaticCell` storage, task state). */
    statics?: string;
    /** The `State` struct, as the comment and the definition. */
    state: string;
    /** The whole `setup()` function, signature and body. */
    setup: string;
    /** The whole `main()` function, signature, body and the loop inside it. */
    main: string;
    /** Items that need `State` and so cannot live in the header. */
    footer?: string;
    /** The header's material: type aliases, constants, helper types, functions and macros. */
    material: string;
}

/** A generated sketch, as the two files it is written to. */
export interface SketchFiles {
    main: string;
    header: string;
}

/** The header's banner: the sketch's own, plus the one line that says which half of it this is. */
function headerBanner(banner: string): string {
    return `${banner}\n//
// MainHeader.rs — the sketch's header. Every \`use\` (include) lives here, re-exported, so the single
// \`use main_header::*;\` at the top of main.rs brings them all into scope. The type aliases, constants,
// helper types, functions and macros that main.rs would otherwise have to carry live here too.
//
// \`use … as _;\` imports are deliberately *not* here: they install a handler or a logger where they are
// compiled, so they stay in the crate root (main.rs).`;
}

/** Assembles `src/main.rs` and `src/MainHeader.rs` from one description of the sketch. */
export function sketchFiles(parts: SketchParts): SketchFiles {
    const sideEffects = parts.sideEffects.length === 0
        ? ''
        : `\n${parts.sideEffects.join('\n')}\n`;
    const modules = parts.modules === undefined || parts.modules === '' ? '' : `\n${parts.modules}\n`;
    const statics = parts.statics === undefined || parts.statics === '' ? '' : `\n${parts.statics}\n`;
    const footer = parts.footer === undefined || parts.footer === '' ? '' : `\n${parts.footer}\n`;

    const main = `${parts.banner}

${parts.prologue}
${sideEffects}
${SKETCH_HEADER_MODULE}
${modules}${statics}
${parts.state}

${parts.setup}

${parts.main}${footer}`;

    const header = `${headerBanner(parts.banner)}

${reExported(parts.imports).join('\n')}

${parts.material}`;

    return { main: normalise(main), header: normalise(header) };
}

/**
 * Tidies the assembled text: no runs of blank lines, and exactly one newline at the end.
 *
 * The emitters are templates with optional pieces, so an empty piece leaves a blank line behind. Every
 * generated file has always ended with a single newline and used LF (`t1-logic/esp-boards.test.js` checks it),
 * and the golden snapshots are byte-for-byte, so the tidying is part of the contract rather than cosmetics.
 */
function normalise(text: string): string {
    return `${text
        .replace(/\r\n/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .replace(/\n{3,}/g, '\n\n')
        .replace(/^\n+/, '')
        .replace(/\n+$/, '')}\n`;
}

/**
 * The block every generated `main.rs` ends with: where the user's own code goes.
 *
 * A generated project is the *start* of a program, and the one question the two-file layout provokes is
 * "which file do I put my function in?" -- asked in as many words on 2026-10-16. So the answer is written into
 * the file: the sketch is `main.rs` plus the header, a function that needs the hardware takes `state`, and the
 * example is a real one for this board (see `exampleFunction`).
 *
 * Plain words rather than backticks around the names: these are Rust comments, and a backtick inside the
 * template literal that writes them is the trap that has already cost this generator an afternoon.
 */
export function codeGuidance(example: SketchExample): string {
    return `// --- Your own code goes below this line ---------------------------------------------------------
//
// The sketch is this file plus MainHeader.rs. Everything above is the shape of it: State is what setup()
// created, and main() is the loop you edit. Rust does not mind about the order of items, so adding your
// functions below main() leaves the top of the file as the shape of the sketch.
//
// A function that needs the hardware takes state, or one of its fields:
//
${example.lines}
//
// ...and is called from the loop with ${example.name}(&mut state).await;, or once from the end of setup()
// if it should only run at start-up.
//
// Anything that does not touch the hardware -- a conversion, a formula, a lookup table -- reads better in
// MainHeader.rs beside the other helpers, where it is reachable from here and from setup(). And a driver
// of your own that outgrows a couple of functions deserves its own file: put it in src/my_driver.rs and
// add mod my_driver; up with mod main_header;.`;
}

/**
 * The block every generated `MainHeader.rs` ends with: what belongs in the header, and what does not.
 *
 * The visibility rule is the half people get wrong, and it is invisible until it fails: `main.rs` reaches the
 * header through `use main_header::*;`, and a glob import only brings in items visible to *it* -- so a helper
 * written here without `pub` cannot be called from `main.rs` at all.
 */
export function headerGuidance(): string {
    return `// --- A helper of your own ---------------------------------------------------------------------
//
// Shared plumbing belongs in this file: the imports above, type aliases, constants, and helpers that do not
// touch the hardware. One thing to remember about the direction of visibility: main.rs reaches this file
// with use main_header::*;, and a glob import only brings in items that are visible to the crate root -- so
// a helper here has to be pub (or pub(crate)) to be callable from main.rs.
//
//     /// Millivolts from a raw 12-bit reading, with a 3.3 V reference.
//     pub fn millivolts(raw: u16) -> u32 {
//         (u32::from(raw) * 3300) / 4095
//     }
//
// Anything that needs the sketch's state belongs in main.rs beside setup() and main() instead: a helper here
// would have to name crate::State, and it could not see main.rs's statics.`;
}

/** One example function, as the guidance block writes it. */
export interface SketchExample {
    /** The function's name, so the sentence after the example can call it by name. */
    name: string;
    /** The commented-out function, already prefixed with `// `. */
    lines: string;
}

/**
 * A commented-out example function for the guidance block, naming a peripheral this board really has.
 *
 * An example that says `state.led` on a board whose LED is `led_red`, that blinks a LED on a board which has
 * none, or that reaches for the display's backlight pin, teaches the wrong lesson in the very first file a
 * user reads -- so the field is chosen from `State`'s own names: `led` first, then a `led_*` channel, then the
 * channels of a tri-colour LED, then any output that is not merely being kept alive. A Pico W's LED is a GPIO
 * on the wireless chip rather than an `Output`, so that case gets its own form; a board with nothing to blink
 * (a panel project, the heartbeat boards) gets one that names no peripheral at all.
 *
 * `ledIndex` is the wireless chip's LED, which is what `gpio_set` takes.
 */
export function exampleFunction(fields: readonly StateField[], ledIndex = 0): SketchExample {
    const names = fields
        .filter((field) => field.keepAlive !== true)
        .map((field) => field.name);
    const output =
        names.find((name) => name === 'led') ??
        names.find((name) => name.startsWith('led_')) ??
        names.find((name) => name === 'red' || name === 'green' || name === 'blue') ??
        fields.find((field) => field.keepAlive !== true && field.type.includes('Output<'))?.name;
    const wireless = fields.find((field) => field.type === 'Cyw43Control')?.name;
    const indented = (lines: readonly string[], name: string): SketchExample => ({
        name,
        lines: lines.map((line) => `//     ${line}`).join('\n'),
    });

    if (output !== undefined) {
        return indented(
            [
                '/// Three quick blinks, using the output setup() brought up.',
                'async fn blink_three(state: &mut State) {',
                '    for _ in 0..3 {',
                `        state.${output}.set_high();`,
                '        Timer::after_millis(120).await;',
                `        state.${output}.set_low();`,
                '        Timer::after_millis(120).await;',
                '    }',
                '}',
            ],
            'blink_three',
        );
    }
    if (wireless !== undefined) {
        return indented(
            [
                '/// Three quick blinks of the on-board LED, which here is a GPIO on the wireless chip.',
                'async fn blink_three(state: &mut State) {',
                '    for _ in 0..3 {',
                `        state.${wireless}.gpio_set(${ledIndex}, true).await;`,
                '        Timer::after_millis(120).await;',
                `        state.${wireless}.gpio_set(${ledIndex}, false).await;`,
                '        Timer::after_millis(120).await;',
                '    }',
                '}',
            ],
            'blink_three',
        );
    }
    return indented(
        [
            '/// A step of your own: whatever setup() brought up is in state.',
            'async fn step(state: &mut State) {',
            '    // Drive something in state here -- a display, a sensor, the radio.',
            '    Timer::after_millis(120).await;',
            '}',
        ],
        'step',
    );
}

/** One field of the generated `State` — one peripheral, or one piece of state the loop keeps. */
export interface StateField {
    name: string;
    /** The Rust type, as it is written in the struct. */
    type: string;
    /** A sentence or two for the `///` comment above the field. */
    doc: string;
    /**
     * True for hardware that must merely stay alive.
     *
     * Dropping a Wi-Fi controller deinitialises the radio, and a `Display` left in a local would be dropped
     * when `setup()` returns — so these fields are read by nobody and say so, rather than tripping the
     * `dead_code` lint in the user's own project.
     */
    keepAlive?: boolean;
    /**
     * Attributes to place above the field, after `#[allow(dead_code)]` when `keepAlive` is set.
     */
    attributes?: string[];
    /**
     * True when `setup()` itself mutates the value before handing it over.
     *
     * `setup()` builds a local and moves it into the struct, so the local needs no `mut` at all unless the
     * bring-up code mutates it in place -- a `RefCellDevice` that is read once for the idle baseline, a
     * `FlashStorage` the calibration is loaded from, a Wi-Fi controller that is told to connect. Every other
     * local is only ever built and moved, and `let mut` on those is a warning in the user's own project.
     */
    mutableInSetup?: boolean;
}

/** The `State` struct: every peripheral `setup()` created, and every value the loop keeps between frames. */
export function stateStruct(doc: string, fields: readonly StateField[]): string {
    const body = fields
        .map((field) => {
            const attributes = [
                ...(field.keepAlive === true ? ['#[allow(dead_code)]'] : []),
                ...(field.attributes ?? []),
            ];
            const lines = [
                ...docComment(field.doc, '    '),
                ...attributes.map((line) => `    ${line}`),
                `    ${field.name}: ${field.type},`,
            ];
            return lines.join('\n');
        })
        .join('\n\n');
    return `${docComment(doc, '').join('\n')}
pub struct State {
${body}
}`;
}

/** A `///` comment block for some text, at the given indentation. */
export function docComment(text: string, indent: string): string[] {
    return text
        .replace(/\s+$/, '')
        .split('\n')
        .map((line) => `${indent}/// ${line}`.trimEnd());
}

/**
 * Drops the `mut` from the locals that become `State` fields, unless `setup()` mutates them itself.
 *
 * A field's local is built once and moved into the struct, so `let mut` on it is an `unused_mut` warning in a
 * project the user has just created — and a generated project that warns on its first build reads as broken.
 * The exceptions are declared on the field (`mutableInSetup`) rather than guessed from the text.
 */
export function immutableLocals(text: string, fields: readonly StateField[]): string {
    return fields.reduce(
        (code, field) =>
            field.mutableInSetup === true
                ? code
                : code.replace(
                    new RegExp(`^(\\s*)let mut ${field.name}\\b`, 'gm'),
                    (_, indent: string) => `${indent}let ${field.name}`,
                ),
        text,
    );
}

/**
 * The `setup()` function: the one-time half of the sketch.
 *
 * `body` is everything it does after the crate's own boot sequence, which the caller writes; `fields` is what
 * it hands back, in the order the struct declares them.
 */
export function setupFn(options: {
    doc: string;
    /** The parameter list, without parentheses: `spawner: Spawner`, or empty. */
    params?: string;
    /** The statements, already indented by four. */
    body: string;
    fields: readonly StateField[];
}): string {
    const returns = options.fields.length === 0
        ? '    State {}'
        : `    State {\n${options.fields.map((field) => `        ${field.name},`).join('\n')}\n    }`;
    return `${docComment(options.doc, '').join('\n')}
pub async fn setup(${options.params ?? ''}) -> State {
${options.body}
${returns}
}`;
}

/**
 * The `main()` function: call `setup()` once, then run the implementation.
 *
 * The loop is *inside* `main()` rather than a helper beside it, which is what was asked for: an Arduino
 * sketch's `loop()` is one function holding the body, and a `main()` that only dispatches to `app_loop()`
 * would be a third thing to look at.
 */
export function mainFn(options: {
    doc: string;
    /** The entry attribute: `#[esp_rtos::main]`, `#[embassy_executor::main]`. */
    attribute: string;
    /** The full signature, e.g. `async fn main(spawner: Spawner)`. */
    signature: string;
    /** The call to `setup()`, e.g. `setup(spawner).await` or `setup().await`. */
    setupCall: string;
    /** Statements between `let … = setup()` and the loop, already indented by four. */
    prelude?: string;
    /** The loop's body, already indented by eight. */
    loop: string;
    /**
     * False when the loop only ever reads `state`.
     *
     * `let mut state` on a loop that never mutates it is an `unused_mut` warning in the user's own project,
     * and a generated project that warns on its first build reads as broken.
     */
    mutable?: boolean;
    /**
     * True when the loop does not name `state` at all.
     *
     * The sketch still keeps it — that is what holds a driver alive for as long as the firmware runs — but the
     * binding has to be `_state`, or rustc says the variable setup() handed over is never used.
     */
    unusedState?: boolean;
    /**
     * False when the entry point is allowed to return.
     *
     * The ESP entry point is `-> !` by construction; embassy's `main` on a Cortex-M target returns `()` and
     * the runtime parks the core when it does.
     */
    diverges?: boolean;
}): string {
    const prelude = options.prelude === undefined || options.prelude === ''
        ? ''
        : `\n\n${options.prelude}`;
    const binding = options.unusedState === true ? '_state' : options.mutable === false ? 'state' : 'mut state';
    return `${docComment(options.doc, '').join('\n')}
${options.attribute}
${options.signature}${options.diverges === false ? '' : ' -> !'} {
    let ${binding} = ${options.setupCall};
${prelude}

    loop {
${options.loop}
    }
}`;
}

/** The marker a body template puts where `loop {` was: everything above it is `setup()`'s half. */
const LOOP_MARKER = '//@loop';/** The marker that closes the loop, in place of the `}` that would otherwise end it. */
const LOOP_END = '//@end';

/** The marker pair a body uses to say "this region belongs in MainHeader.rs". */
const HEADER_MARKER = '//@header';
const HEADER_END = '//@header-end';

/**
 * Moves the regions a body marked `//@header … //@header-end` out of `main.rs` and into the header.
 *
 * The helper types, constants and functions a body needs are written where they are used, which is the right
 * place to read them; they just do not *belong* there once `main.rs` is a sketch, so the regions are lifted
 * out and dedented by the four spaces they had inside a function.
 *
 * Two things have to change as they move, and both are done here rather than by hand at each site:
 *
 * - **every item becomes `pub`** — the header is a *child* module, so `use main_header::*;` in the crate root
 *   cannot see anything private, and a sketch's helpers are meant to be visible;
 * - **a `macro_rules!` gains a `pub(crate) use`** — a macro is not an item a `use` can reach until it is
 *   re-exported, which is the idiom the crate's own header uses.
 */
export function hoistHeader(body: string): { body: string; material: string } {
    const kept: string[] = [];
    const regions: string[][] = [];
    let current: string[] | undefined;
    for (const line of body.split('\n')) {
        const trimmed = line.trim();
        if (trimmed === HEADER_MARKER) {
            current = [];
            regions.push(current);
            continue;
        }
        if (trimmed === HEADER_END) {
            current = undefined;
            continue;
        }
        if (current === undefined) {
            kept.push(line);
        } else {
            current.push(line.startsWith('    ') ? line.slice(4) : line);
        }
    }
    const material = regions
        .map((region) => publicItems(trim(region.join('\n'))))
        .filter((text) => text !== '')
        .join('\n\n');
    return { body: trim(kept.join('\n')), material };
}

/** Strips the blank lines from both ends of a block. */
function trim(text: string): string {
    return text.replace(/^\n+/, '').replace(/\s+$/, '');
}

/** Makes every item in a hoisted region public, and re-exports any macro it declares. */
function publicItems(text: string): string {
    const out: string[] = [];
    const macros: string[] = [];
    let depth = 0;
    // True while inside an `impl <Type> { … }` of our own -- an inherent impl, whose methods have to be public
    // to be reachable through `use main_header::*`. A *trait* impl is different: a visibility qualifier on a
    // trait method is a hard error (E0449), so those are left exactly as they were.
    let inherentImpl = false;
    let structFields = false;
    for (const line of text.split('\n')) {
        const trimmed = line.trim();
        if (/^impl\b/.test(trimmed) && !/\bfor\b/.test(trimmed)) {
            inherentImpl = true;
        }
        if (/^(pub )?struct\b/.test(trimmed) && trimmed.endsWith('{')) {
            structFields = true;
        }
        const item = /^(async )?(fn|const|static|struct|enum|type|trait)\s/.test(line);
        const method = inherentImpl && /^\s+(async )?fn\s/.test(line);
        // A struct's fields are private by default too, and `main.rs` sets and reads them.
        const field = structFields && /^\s+[A-Za-z_][A-Za-z0-9_]*:/.test(line);
        out.push(
            item || method
                ? line.replace(/^(\s*)(async )?(fn|const|static|struct|enum|type|trait)/, '$1pub $2$3')
                : field
                    ? line.replace(/^(\s*)/, '$1pub ')
                    : line,
        );
        const macro = /^macro_rules!\s+([A-Za-z0-9_]+)/.exec(trimmed)?.[1];
        if (macro !== undefined) {
            macros.push(macro);
        }
        depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
        if (inherentImpl && depth <= 0) {
            inherentImpl = false;
        }
        if (structFields && depth <= 0) {
            structFields = false;
        }
    }
    return [...out, ...macros.map((name) => `\npub(crate) use ${name};`)].join('\n');
}

/** The same, for header material a template writes as its own string rather than marking in a body. */
export function publicHeaderItems(text: string): string {
    return publicItems(text.replace(/^\n+/, '').replace(/\s+$/, ''));
}

/**
 * Splits a template's body into the half that initialises and the half that repeats.
 *
 * The bodies are the same Rust they always were — they are written once and read as one piece — so the split
 * is marked rather than re-typed: a body carries `//@loop` where its `loop {` was and `//@end` where that
 * loop's closing brace was, and the two halves come out dedented by four and ready for `setup()` and `main()`.
 *
 * A body with no marker is a body with no loop (the Bluetooth template hands its controller to the host stack
 * and never loops), and comes back whole as the initialisation half. A body with one marker and no other is a
 * mistake in the generator, so it throws rather than emitting a project that does not compile.
 */
export function splitAtLoop(body: string): { init: string; loop: string } {
    const lines = body.split('\n');
    const start = lines.findIndex((line) => line.trim() === LOOP_MARKER);
    const end = lines.findIndex((line) => line.trim() === LOOP_END);
    if (start === -1 && end === -1) {
        return { init: body, loop: '' };
    }
    if (start === -1 || end === -1 || end < start) {
        throw new Error('the generated body has a loop marker without its end (or the other way round)');
    }
    // Neither half is re-indented: `setup()`'s statements were already written at the four spaces a function
    // body uses, and the loop's were written at the eight an already-indented `loop {` gave them.
    return {
        init: lines.slice(0, start).join('\n').replace(/\n\s*$/, ''),
        loop: lines.slice(start + 1, end).join('\n').replace(/^\n+/, '').replace(/\n\s*$/, ''),
    };
}
/**
 * Rewrites a loop body written against bare local names into one written against `state.<field>`.
 *
 * `setup()` creates the peripherals as ordinary locals and hands them back in a `State`; the loop reads and
 * writes those same values, so every mention of one has to become a field access. Doing that by hand across
 * several hundred lines of drawing code is how a mistake gets shipped, so it is done here, once, over the
 * text — with string literals, character literals and comments left strictly alone, because a log message
 * that says "corner" is not a variable.
 *
 * Left alone as well are:
 *
 * - a name already reached through something else (`info.ssid`, `layout.width`) — the character before it is
 *   a `.`, so it belongs to that receiver, not to the sketch's own state;
 * - the name being *bound* by a `let`, which is a fresh local shadowing the field on purpose;
 * - a path segment (`touch::something`).
 */
export function againstState(text: string, fields: readonly string[]): string {
    const names = new Set(fields);
    let out = '';
    let index = 0;
    while (index < text.length) {
        const char = text.charAt(index);
        // Comments, string literals and character literals are copied through untouched: a word in a log
        // message or a doc comment is text, not a name.
        if (char === '/' && text.charAt(index + 1) === '/') {
            const end = text.indexOf('\n', index);
            out += end === -1 ? text.slice(index) : text.slice(index, end);
            index = end === -1 ? text.length : end;
            continue;
        }
        if (char === '/' && text.charAt(index + 1) === '*') {
            const end = text.indexOf('*/', index + 2);
            out += end === -1 ? text.slice(index) : text.slice(index, end + 2);
            index = end === -1 ? text.length : end + 2;
            continue;
        }
        if (char === '"' || char === '\'') {
            const end = literalEnd(text, index);
            out += text.slice(index, end);
            index = end;
            continue;
        }
        if (/[A-Za-z_]/.test(char)) {
            let end = index + 1;
            while (end < text.length && /[A-Za-z0-9_]/.test(text.charAt(end))) {
                end += 1;
            }
            const word = text.slice(index, end);
            // The neighbours are taken from this line only. Taking them from the whole text up to here reads
            // the end of the previous line -- a comment that ends in a full stop, say -- and would decide the
            // name was reached through something else (`microseconds. ticks = …` looks exactly like
            // `info.ssid`), which is how `ticks = …` at the start of a line was left unqualified once.
            const lineStart = text.lastIndexOf('\n', index - 1) + 1;
            const before = text.slice(lineStart, index).replace(/\s+$/, '');
            const previous = before.charAt(before.length - 1);
            const after = text.slice(end).replace(/^\s+/, '');
            const bound = /\blet\s+(mut\s+)?$/.test(before);
            const projectable =
                names.has(word) &&
                previous !== '.' &&
                !after.startsWith('::') &&
                !bound;
            out += projectable ? `state.${word}` : word;
            index = end;
            continue;
        }
        out += char;
        index += 1;
    }
    return out;
}

/**
 * The end of the string literal (or character literal) that starts at `start`, exclusive.
 *
 * Written out rather than regexed because the bodies carry escaped quotes — `"\""` in the escaping test, and
 * `expect(\"…\")` inside generated Rust — and a naive scan would end the literal in the middle of one.
 */
function literalEnd(text: string, start: number): number {
    const quote = text.charAt(start);
    let index = start + 1;
    while (index < text.length) {
        const char = text.charAt(index);
        if (char === '\\') {
            index += 2;
            continue;
        }
        if (char === quote) {
            return index + 1;
        }
        index += 1;
    }
    return text.length;
}


