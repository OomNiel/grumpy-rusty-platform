/* Backing the project folder up, as a sibling in its parent folder (asked 2026-10-05).
 *
 * *"Add a control there to back up the project folder (project folder name plus date stamp) in its parent
 * folder."* So the copy lands next to the project — `/home/me/proj` becomes `/home/me/proj-2026-10-05_1804` —
 * which is where a person looks for it, and without asking for a destination every time.
 *
 * WHAT IS LEFT OUT, AND WHY IT IS THE ONLY REAL DECISION. `target/` is not part of the project: it is what the
 * compiler produced, it is routinely tens of gigabytes for an embedded workspace, and it is regenerated by the
 * next build. A backup that copied it would be slow, huge, and would bury the files that matter. `.git/` is the
 * opposite — it *is* the project's history, and a backup without it is a snapshot of the last commit plus
 * uncommitted work, not a backup — so it is copied. The rest of the exclusion list is the same set of built
 * artifacts the rest of the extension already ignores (`node_modules`, the DSH session worktrees).
 */

import * as path from 'path';

/** Directory names never worth copying into a backup, anywhere in the tree. */
export const BACKUP_SKIP_DIRS: readonly string[] = ['target', 'node_modules', '.dsh-worktrees'];

/**
 * Whether one entry should be copied: the pure half of the filter `fs.cpSync` takes.
 *
 * `target` is skipped as a *directory*; a **file** called `target` (a script someone wrote, say) is the user's
 * own work and is copied. The distinction needs to know which it is, hence the second argument.
 */
export function shouldCopyEntry(name: string, isDirectory: boolean): boolean {
    if (!name) return true;
    if (isDirectory && BACKUP_SKIP_DIRS.includes(name)) return false;
    return true;
}

/** `2026-10-05_1804` — date first, so two backups of one project sort in the order they were taken. */
export function backupStamp(date: Date = new Date()): string {
    const p = (n: number): string => String(n).padStart(2, '0');
    return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}_${p(date.getHours())}${p(date.getMinutes())}${p(date.getSeconds())}`;
}

/**
 * The folder to create: the project's own name plus the stamp.
 *
 * `taken` is the set of names already in the parent folder, so a second backup inside the same second gets
 * `-2` rather than overwriting the first one — the alternative is a backup that silently replaces a backup.
 */
export function backupFolderName(projectName: string, date: Date = new Date(), taken: readonly string[] = []): string {
    const clean = String(projectName ?? '').trim().replace(/[/\\:]+/g, '-').replace(/^\.+/, '') || 'project';
    const base = `${clean}-${backupStamp(date)}`;
    if (!taken.includes(base)) return base;
    for (let n = 2; n < 100; n += 1) {
        const candidate = `${base}-${n}`;
        if (!taken.includes(candidate)) return candidate;
    }
    return `${base}-${taken.length + 1}`;
}

/** The one-line description of what a backup will do, shown before it runs and after it finishes. */
export function backupPlanLine(projectRoot: string, destination: string): string {
    // The destination's **full** path, not just its name: the whole point of the line is "where is it going",
    // and a progress message that says `me/proj-2026-…` answers a question nobody asked.
    return `Copy ${path.basename(projectRoot)} → ${destination}, leaving out ${BACKUP_SKIP_DIRS.join(', ')}`;
}
